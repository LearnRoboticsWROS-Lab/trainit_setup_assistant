"""The final canonical COMPOSITION end-to-end of M3, LAUNCHED (opt-in): the M3.7 composition program --
``test/data/m3_7/composition.yaml``, several tasks, task calls and the three control steps on the public
UR5e sample cell -- generated by the TSA under test into a temp workspace, built, brought up on mock and
run (vNext M3.7, ADR-0024).

    generate it from its directory, renamed to m37_* so it never collides with a bundle the user built
      -> colcon build over the sourced workspace: 3 packages
      -> ``ros2 launch m37_app bringup.launch.py mode:=mock rviz:=false``: move_group ready, the arm
         controller active, the trainit_mock adapter for /eef/main up
      -> ``ros2 launch m37_app trainit_bt.launch.py use_sim_time:=false groot_monitor:=false``: MainTree
         adds the table and runs task_cell_cycle -- HOME, the conveyor on, a REPEAT of 2 calls of task
         `transfer` (grasp at the taught pick: PreGrasp, Approach, close, verify held, Retract; release
         at the taught place: PreRelease, Approach, verify held, open, verify released, Retract), the
         conveyor off, then a FALLBACK whose first alternative is a RETRY of 2 tries of a PTP to
         `out_of_reach` (1.5 m from the base: MoveIt refuses the target twice -- a TARGET failure, no
         fault) so its second alternative, a call of task `go_home`, runs -- and ends
         ``BT finished: SUCCESS`` with exit 0 (no end-effector fault latched)
      -> both launches end within 30 s of their SIGINT and leave no process; ROS domain 76 holds no node
         before and none after

OPT-IN: ``TRAINIT_LAUNCH_TEST=1`` and a sourced workspace (ROS 2 Humble + the TrainIt workspace with the
trainit_motion_runtime the generated package.xml declares). It skips, naming the cause, with an older
trainit_motion_runtime or trainit_hardware_layer than declared, without ur_description and xacro, or when
the machine lacks what the bundle declares (``launch_prereqs``). Every launch runs in its own session on
ROS domain 76 (no other TrainIt test uses it), ROS_LOCALHOST_ONLY=1, with TMPDIR and ROS_LOG_DIR inside
the temp workspace. Test-time generation, removed at teardown. With ``TRAINIT_M37_EVIDENCE=<dir>`` the
report and every launch log are copied to ``<dir>/m3_7_e2e/``.
"""
import os
import re
import shutil
import xml.etree.ElementTree as ET
from pathlib import Path

import pytest

pytestmark = pytest.mark.skipif(os.environ.get('TRAINIT_LAUNCH_TEST') != '1',
                                reason='opt-in: set TRAINIT_LAUNCH_TEST=1 (builds and launches)')

_NO_SOLUTION = 'no collision-free joint solution for the pose'   # TMR 2.6.0's resolver (ADR-0028)
DATA = Path(__file__).resolve().parent / 'data' / 'm3_7'
PREFIX = 'm37'
DOMAIN = 76
EVIDENCE = 'TRAINIT_M37_EVIDENCE'
TRANSFER = ['transfer__s1_pregrasp', 'transfer__s1_grasp', 'transfer__s1_retract',
            'transfer__s2_prerelease', 'transfer__s2_release', 'transfer__s2_retract']
MOVES = ['home'] + TRANSFER + TRANSFER + ['out_of_reach', 'out_of_reach', 'home']
EVENT = re.compile(r"(added collision box '\w+'|MoveWaypoint '\w+'(?= \()|\[process\] \w+ channel='\w+'"
                   r"|BT finished: \w+)")
NEVER = ('REFUSED', 'NOT_AT_PATH_START', 'FRAME_UNRESOLVED', 'is not a loaded motion profile',
         'VALIDATION FAILED', 'Found a contact between', '[FATAL]',
         'FAULT latched', 'MOTION_FAULT', 'exit code 3')


def _sample_launch():
    import test_example_ur5e_suction_launch as S
    return S


class CompositionLaunch:
    """The bring-up, then the runner, on the composition bundle built in ws (the sample's harness, on
    its own domain and package names)."""

    def __init__(self, ws: Path):
        self.base = _sample_launch().SampleLaunch(ws)
        self.base.env['ROS_DOMAIN_ID'] = str(DOMAIN)

    def run(self) -> 'CompositionLaunch':
        S, b = _sample_launch(), self.base
        saved = (S.DOMAIN, S.PREFIX)
        S.DOMAIN, S.PREFIX = DOMAIN, PREFIX     # the harness's guards and launches, ours
        try:
            b.run()
        finally:
            S.DOMAIN, S.PREFIX = saved
        runner_log = b.logs / 'runner.log'
        self.runner = runner_log.read_text(errors='replace') if runner_log.is_file() else ''
        bringup_log = b.logs / 'bringup.log'
        self.bringup = bringup_log.read_text(errors='replace') if bringup_log.is_file() else ''
        self.events = EVENT.findall(self.runner)
        self.moves = re.findall(r"\]: MoveWaypoint '(\w+)' \(", self.runner)
        self.verify_lines = [line for line in self.runner.splitlines() if 'VerifyGrasp' in line]
        # the retry's two tries: the only motions MoveIt may refuse
        # TMR 2.6.0 (ADR-0028): a PTP to a pose with no IK solution is refused by the runtime's own resolver
        # (NO_IK_SOLUTION, the plan phase: the same TARGET failure) before Pilz is asked
        self.plan_failed = [line for line in self.runner.splitlines()
                            if 'PLAN FAILED' in line or _NO_SOLUTION in line]
        self.never = sorted(n for n in NEVER if n in self.runner or n in self.bringup)
        for line in (f'[runner] events {self.events}', f'[runner] moves {self.moves}',
                     f'[runner] VerifyGrasp lines {len(self.verify_lines)}',
                     f'[runner] PLAN FAILED lines {self.plan_failed}',
                     f'[logs] lines that must never appear: {self.never or "none"}'):
            b.say(line)
        return self

    def report(self) -> str:
        return self.base.report()


@pytest.fixture(scope='module')
def e2e(tmp_path_factory):
    import composite_launch as CL
    if not os.environ.get('COLCON_PREFIX_PATH'):
        pytest.skip('needs a sourced workspace (ROS 2 Humble + the TrainIt workspace install)')
    import test_example_ur5e_suction as S
    S.needs_ur_description()
    from trainit_setup_assistant.generator import Orchestrator
    from trainit_setup_assistant.model import BundleSpec, load_project
    tmp = tmp_path_factory.mktemp('m37_ws')
    try:
        ws = CL._outside_the_underlay(tmp)
        with pytest.MonkeyPatch.context() as mp:
            mp.chdir(DATA)
            project = load_project('composition.yaml')
            project.bundle = BundleSpec.from_prefix(PREFIX)
            manifest = Orchestrator().generate(project, ws / 'src' / PREFIX)
        app_xml = ws / 'src' / PREFIX / f'{PREFIX}_app' / 'package.xml'
        floors = {e.text.strip(): tuple(int(x) for x in e.get('version_gte').split('.'))
                  for e in ET.parse(app_xml).getroot().iter('exec_depend')
                  if e.get('version_gte')}
        for package, floor in sorted(floors.items()):
            have = CL.installed_version(package)
            if have < floor:
                pytest.skip(f'{package} {CL._v(have)} is installed; the bundle declares '
                            f'>= {CL._v(floor)}')
        import launch_prereqs
        launch_prereqs.require(ws / 'src', modules=CL.PROBE_MODULES)
        summary = CL.build(ws)
        tree = (ws / 'src' / PREFIX / f'{PREFIX}_app' / 'bt_trees' / 'task_program.xml').read_text()
        run = CompositionLaunch(ws)
        try:
            run.run()
        finally:
            if os.environ.get(EVIDENCE):
                dest = Path(os.environ[EVIDENCE]) / 'm3_7_e2e'
                run.base.save(dest)
                (dest / 'task_program.xml').write_text(tree)
        yield dict(manifest=manifest, summary=summary, run=run, floors=floors, tree=tree)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def _why(e2e) -> str:
    return '\n' + e2e['run'].report()


def test_e2e_the_composition_generates_and_builds(e2e):
    assert e2e['manifest'].warnings == []
    assert '3 packages finished' in e2e['summary'], e2e['summary']
    tree = e2e['tree']
    for node in ('<SubTree ID="task_cell_cycle"', '<Repeat num_cycles="2">', '<SubTree ID="task_transfer"',
                 '<Fallback>', '<RetryUntilSuccessful num_attempts="2">', '<SubTree ID="task_go_home"'):
        assert node in tree, node


def test_e2e_the_bring_up_comes_up_on_mock(e2e):
    ready = e2e['run'].base.ready
    assert ready and all(ready.values()), _why(e2e)


def test_e2e_the_composition_ends_bt_finished_success(e2e):
    b = e2e['run'].base
    assert (b.timed_out, b.finished, b.code) == (False, 'SUCCESS', 0), _why(e2e)


def test_e2e_the_calls_and_control_steps_run_in_the_programs_order(e2e):
    run = e2e['run']
    # HOME, two calls of transfer (the repeat), then -- the retry's two failed verifications making
    # the fallback take its second alternative -- the call of go_home: HOME
    assert run.moves == MOVES, _why(e2e)
    assert run.events == (["added collision box 'table'", "MoveWaypoint 'home'",
                           "[process] ENABLE channel='conveyor'"]
                          + [f"MoveWaypoint '{w}'" for w in TRANSFER * 2]
                          + ["[process] DISABLE channel='conveyor'", "MoveWaypoint 'out_of_reach'",
                             "MoveWaypoint 'out_of_reach'", "MoveWaypoint 'home'", 'BT finished: SUCCESS']), _why(e2e)
    # the retry's two tries are the only refused targets: Pilz PTP finds no IK solution (code -31),
    # a TARGET failure -- no fault is written or latched (exit 0 above)
    assert len(run.plan_failed) == 2, _why(e2e)
    assert all('planner=PTP, code=-31' in line or _NO_SOLUTION in line for line in run.plan_failed), _why(e2e)


def test_e2e_no_log_names_a_refusal_a_failed_motion_a_fault_or_a_contact(e2e):
    assert e2e['run'].never == [], _why(e2e)


def test_e2e_every_launch_ends_cleanly_and_the_domain_is_empty_before_and_after(e2e):
    b = e2e['run'].base
    assert b.guards == {'before': [], 'after': []}, _why(e2e)
    assert b.stops == {'runner': 'clean', 'bring-up': 'clean'}, _why(e2e)
