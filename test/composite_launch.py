# --- generation and build -------------------------------------------------------------------------

def tree_sha256(root: Path) -> str:
    """sha256 over the sorted relative paths and file sha256s of a generated tree."""
    h = hashlib.sha256()
    for f in sorted(p for p in Path(root).rglob('*') if p.is_file()):
        h.update(f'{f.relative_to(root)}\0{hashlib.sha256(f.read_bytes()).hexdigest()}\n'.encode())
    return h.hexdigest()


def _prefixes(variable: str) -> list:
    """The entries of a sourced path list (COLCON_PREFIX_PATH, AMENT_PREFIX_PATH), resolved."""
    return [Path(p).resolve() for p in os.environ.get(variable, '').split(os.pathsep) if p]


def _underlay() -> Path:
    """The innermost sourced workspace's install (the first COLCON_PREFIX_PATH entry): the cells
    are built over it and run with its setup.bash, which sources the workspaces below it."""
    prefixes = _prefixes('COLCON_PREFIX_PATH')
    if not prefixes:
        raise RuntimeError('no sourced workspace (COLCON_PREFIX_PATH is empty)')
    return prefixes[0]


def _sourced_workspaces() -> list:
    """The root of EVERY sourced workspace, sorted: the parent of each COLCON_PREFIX_PATH entry
    (an install base), and for each AMENT_PREFIX_PATH entry the parent of the colcon install base
    that holds it (the entry itself when merged, its parent when isolated: the one with a
    .colcon_install_layout); an entry no colcon install base holds (/opt/ros/<distro>) is its own
    root."""
    roots = {p.parent for p in _prefixes('COLCON_PREFIX_PATH')}
    for prefix in _prefixes('AMENT_PREFIX_PATH'):
        base = next((b for b in (prefix, prefix.parent)
                     if (b / '.colcon_install_layout').is_file()), None)
        roots.add(base.parent if base is not None else prefix)
    return sorted(roots)


def _outside_the_underlay(ws: Path) -> Path:
    """ws, resolved -- refused when it lies inside ANY sourced workspace (not only the innermost:
    with an overlay sourced on top, the workspace below it must stay untouched too): generated
    packages, build/ and install/ must never land in one."""
    ws = Path(ws).resolve()
    _underlay()                                  # a sourced workspace is required
    for root in _sourced_workspaces():
        if ws == root or root in ws.parents:
            raise RuntimeError(f'refused: {ws} is inside the sourced workspace {root}')
    return ws


def generate(ws: Path) -> list:
    """The three cells into ws/src/<robot>/ (projects under ws/in/), with the TSA under test.
    Returns one identity line per bundle (app package, tree sha256, file count)."""
    from trainit_setup_assistant.generator import Orchestrator
    ws = _outside_the_underlay(ws)
    out = []
    for ns, robot, p in CELLS:
        project = F.composite_mock(ws / 'in' / robot, robot, ns, prefix=p)
        Orchestrator().generate(project, ws / 'src' / robot)
        tree = ws / 'src' / robot
        out.append(f'{robot:8s} ns={ns or "/":4s} app={project.bundle.app_package} tree sha256 '
                   f'{tree_sha256(tree)} ({sum(1 for q in tree.rglob("*") if q.is_file())} files)')
    (ws / 'bundles.txt').write_text('\n'.join(out) + '\n')
    return out


def _sourced(*extra) -> str:
    distro = os.environ.get('ROS_DISTRO', 'humble')
    parts = [f'/opt/ros/{distro}/setup.bash', str(_underlay() / 'setup.bash')] + list(extra)
    return ' && '.join(f'source {shlex.quote(p)}' for p in parts)


def build(ws: Path) -> str:
    """colcon build of ws/src over the sourced workspace, build/ install/ log/ inside ws (never a
    symlink install: the injection edits an installed COPY). Returns colcon's summary line."""
    ws = _outside_the_underlay(ws)
    q = shlex.quote
    cmd = (f'set -o pipefail; {_sourced()} && cd {q(str(ws))} && [ "$(pwd -P)" = {q(str(ws))} ] && '
           f'colcon --log-base {q(str(ws / "log"))} build --base-paths {q(str(ws / "src"))} '
           f'--build-base {q(str(ws / "build"))} --install-base {q(str(ws / "install"))} '
           f'--event-handlers console_cohesion- 2>&1 | tail -5')
    r = subprocess.run(['bash', '-c', cmd], cwd=ws, capture_output=True, text=True, timeout=900)
    if r.returncode != 0 or 'Summary:' not in r.stdout or 'failed' in r.stdout:
        raise RuntimeError(f'colcon build failed (rc {r.returncode}):\n{r.stdout}{r.stderr}')
    return next(line for line in r.stdout.splitlines() if 'Summary:' in line).strip()


def installed_version(package: str) -> tuple:
    """The <version> of a package's INSTALLED package.xml, as a tuple of ints."""
    from ament_index_python.packages import get_package_share_directory
    text = (Path(get_package_share_directory(package)) / 'package.xml').read_text()
    m = re.search(r'<version>\s*(\d+)\.(\d+)\.(\d+)\s*</version>', text)
    return tuple(int(x) for x in m.groups())


def active_joints(urdf_xml: str) -> list:
    """The joints a joint state must carry: neither fixed nor a mimic follower."""
    root = ET.fromstring(urdf_xml)
    return sorted(j.get('name') for j in root.iter('joint')
                  if j.get('type') != 'fixed' and j.find('mimic') is None)


def _v(version: tuple) -> str:
    return '.'.join(str(x) for x in version)


def _stable(node_name: str) -> str:
    """A node name without the per-process address some libraries append to their internal
    nodes (MoveIt's ``move_group_private_<address>``, tf2's ``transform_listener_impl_<address>``):
    the same node in every run and every cell."""
    return re.sub(r'_[0-9a-f]{8,}$', '_<id>', node_name)


# --- the probe ------------------------------------------------------------------------------------

class _Probe:
    """One rclpy node on a context of its own, on the launch domain, spun by its own thread.
    While it lives the process runs with ROS_LOCALHOST_ONLY=1 and, unless the caller set one, a
    ROS_LOG_DIR inside the workspace (never ~/.ros/log); both are restored on close()."""

    def __init__(self, domain: int, name: str, log_dir: Path):
        import rclpy
        from rclpy.executors import MultiThreadedExecutor
        self._rclpy = rclpy
        self._saved = {k: os.environ.get(k) for k in ('ROS_LOCALHOST_ONLY', 'ROS_LOG_DIR')}
        os.environ['ROS_LOCALHOST_ONLY'] = '1'
        os.environ.setdefault('ROS_LOG_DIR', str(log_dir))
        self.context = rclpy.Context()
        rclpy.init(context=self.context, domain_id=domain)
        self.node = rclpy.create_node(name, context=self.context)
        self.executor = MultiThreadedExecutor(num_threads=4, context=self.context)
        self.executor.add_node(self.node)
        threading.Thread(target=self.executor.spin, daemon=True).start()

    def nodes(self) -> list:
        """Every visible node but hidden ones and this probe, as sorted (namespace, name)."""
        own = (self.node.get_namespace(), self.node.get_name())
        return sorted((ns, n) for n, ns in self.node.get_node_names_and_namespaces()
                      if not n.startswith('_') and (ns, n) != own)

    def close(self) -> None:
        self.executor.shutdown(timeout_sec=5.0)
        # destroy_node() leaves waitables (action clients) alone, and a live action client keeps
        # the node, and so its graph entry, alive: destroy them first
        for waitable in list(self.node.waitables):
            try:
                waitable.destroy()
            except Exception:                     # noqa: BLE001 -- already gone
                pass
        self.node.destroy_node()
        self._rclpy.try_shutdown(context=self.context)
        for key, value in self._saved.items():
            if value is None:
                os.environ.pop(key, None)
            else:
                os.environ[key] = value


def _wait_log(log: Path, pattern: str, timeout_s: float) -> bool:
    end = time.monotonic() + timeout_s
    while time.monotonic() < end:
        text = log.read_text(errors='replace') if log.exists() else ''
        if re.search(pattern, text):
            return True
        time.sleep(0.5)
    return False


