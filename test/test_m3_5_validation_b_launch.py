def write_fake_detector(src: Path) -> None:
    pkg = src / 'm3c_fake_detector'
    (pkg / 'm3c_fake_detector').mkdir(parents=True)
    (pkg / 'resource').mkdir()
    (pkg / 'resource' / 'm3c_fake_detector').write_text('')
    (pkg / 'package.xml').write_text(FAKE_PACKAGE_XML)
    (pkg / 'setup.py').write_text(FAKE_SETUP)
    (pkg / 'setup.cfg').write_text('[install]\ninstall_scripts=$base/lib/m3c_fake_detector\n'
                                   '[develop]\nscript_dir=$base/lib/m3c_fake_detector\n')
    (pkg / 'm3c_fake_detector' / '__init__.py').write_text('')
    (pkg / 'm3c_fake_detector' / 'node.py').write_text(FAKE_NODE)


