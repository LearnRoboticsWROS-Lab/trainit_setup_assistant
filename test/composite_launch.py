class CompositeLaunch:
    """Phases A, B and C on the cells built in ws (generate + build first)."""

    def __init__(self, ws: Path, domain: int = DOMAIN):
        self.ws = _outside_the_underlay(ws)
        self.domain = int(domain)
        self.logdir = self.ws / 'logs'
        self.tmp = self.ws / 'tmp'
        self.ros_log = self.ws / 'ros_log'
        for d in (self.logdir, self.tmp, self.ros_log):
            d.mkdir(parents=True, exist_ok=True)
        self.env = dict(os.environ, ROS_DOMAIN_ID=str(self.domain), ROS_LOCALHOST_ONLY='1',
                        RCUTILS_COLORIZED_OUTPUT='0', ROS_LOG_DIR=str(self.ros_log),
                        TMPDIR=str(self.tmp))
        self.lines = []
        self.checks = []                 # (id, 'PASS' | 'FAIL' | 'SKIPPED', detail)
        self.obs = {ns: {} for ns, _r, _p in CELLS}
        self.contract = {ns: F.composite_mock_contract(p) for ns, _r, p in CELLS}
        self.urdf_active = {}
        self._guards = 0

    # --- the report -------------------------------------------------------------------------
    def say(self, text: str) -> None:
        self.lines.append(text)
        print(text, flush=True)

    def check(self, cid: str, ok, detail: str = '') -> None:
        status = 'SKIPPED' if ok is None else ('PASS' if ok else 'FAIL')
        self.checks.append((cid, status, detail))

    def report(self) -> str:
        return '\n'.join(self.lines) + '\n'

    def save(self, dest: Path) -> None:
        """The report, the bundle identities and every launch log, into dest."""
        dest = Path(dest)
        (dest / 'logs').mkdir(parents=True, exist_ok=True)
        (dest / 'report.txt').write_text(self.report())
        if (self.ws / 'bundles.txt').is_file():
            shutil.copy(self.ws / 'bundles.txt', dest / 'bundles.txt')
        for log in sorted(self.logdir.glob('*.log')):
            shutil.copy(log, dest / 'logs' / log.name)

    # --- processes --------------------------------------------------------------------------
    def _launch(self, what: str, log: Path) -> subprocess.Popen:
        cmd = (_sourced(str(self.ws / 'install' / 'setup.bash')) +
               f' && exec ros2 launch {what} > {shlex.quote(str(log))} 2>&1')
        return subprocess.Popen(['bash', '-c', cmd], env=self.env, start_new_session=True)

    @staticmethod
    def _stop_outcome(proc: subprocess.Popen) -> str:
        """SIGINT to the launch's group (unless the launch has exited already), then how it ended:
        'clean' = it exited within 30 s of the SIGINT and no process of its group outlived it by
        15 s (what T2, test_generated_bundle_launch.py, requires); 'needed SIGKILL' = it was still
        running 30 s after the SIGINT, so its group was SIGKILLed; 'a process survived' = it exited
        but a process of its group was still alive 15 s later (then SIGKILLed)."""
        forced = False
        if proc.poll() is None:
            os.killpg(proc.pid, signal.SIGINT)
            try:
                proc.wait(timeout=30)
            except subprocess.TimeoutExpired:
                forced = True                        # SIGINT did not end it: never clean
                os.killpg(proc.pid, signal.SIGKILL)
                proc.wait()
        end = time.monotonic() + 15
        while time.monotonic() < end:
            try:
                os.killpg(proc.pid, 0)               # anything left in the launch's group?
            except ProcessLookupError:
                return 'needed SIGKILL' if forced else 'clean'
            time.sleep(0.5)
        os.killpg(proc.pid, signal.SIGKILL)
        return 'needed SIGKILL' if forced else 'a process survived'

    @staticmethod
    def _stop(proc: subprocess.Popen) -> bool:
        """SIGINT to the launch's group; True only for a 'clean' _stop_outcome."""
        return CompositeLaunch._stop_outcome(proc) == 'clean'

    def _check_stop(self, cid: str, outcome: str) -> None:
        self.check(cid, outcome == 'clean', '' if outcome == 'clean' else outcome)

    def _stop_all(self, procs: dict, tag: str) -> None:
        outcome = {k: self._stop_outcome(p) for k, p in procs.items()}
        clean = {k: v == 'clean' for k, v in outcome.items()}
        self.say(f'[+{tag}] every process of {sorted(k or "/" for k in clean)} exited after '
                 f'SIGINT: {all(clean.values())}')
        self.check(f'shutdown {tag}', all(clean.values()),
                   ', '.join(f'{k or "/"} {v}' + ('' if v else f' ({outcome[k]})')
                             for k, v in sorted(clean.items())))

    def _probe(self, name: str) -> '_Probe':
        return _Probe(self.domain, name, self.ros_log)

    def _guard(self, tag: str) -> bool:
        # one name per guard: a node left over from an earlier guard is never discounted as "self"
        self._guards += 1
        probe = self._probe(f't13_guard_{self._guards}')
        try:
            time.sleep(SETTLE_S)
            nodes = [f'{ns.rstrip("/")}/{n}' for ns, n in probe.nodes()]
        finally:
            probe.close()
        self.say(f'[+guard] ROS domain {self.domain} {tag}: {nodes or "no node"}')
        self.check(f'guard {tag}', not nodes, f'{len(nodes)} node(s)')
        return not nodes

    # --- the whole run ----------------------------------------------------------------------
    def run(self, phases: str = 'ABC') -> 'CompositeLaunch':
        from trainit_setup_assistant.robotmodel.xacro_loader import compile_xacro
        for ns, robot, _p in CELLS:
            desc = self.ws / 'install' / f'{robot}_description' / 'share' / f'{robot}_description'
            self.urdf_active[ns] = active_joints(
                compile_xacro(desc / 'urdf' / f'{robot}.urdf.xacro'))
        if not self._guard('before the launches'):
            raise RuntimeError(f'ROS domain {self.domain} is not empty: refusing to launch on it')
        try:
            if 'A' in phases:
                self.phase_a()
            if 'B' in phases:
                self.phase_b()
            if 'C' in phases:
                self.phase_c()
        finally:
            self._guard('after the launches')
            for cid, status, detail in self.checks:
                self.say(f'[+verdict] {cid}: {status}{" -- " + detail if detail else ""}')
        return self

    # --- phase A: the three cells at once ------------------------------------------------------
    def phase_a(self) -> None:
        procs, logs = {}, {}
        for ns, robot, p in CELLS:
            logs[ns] = self.logdir / f'bringup{ns.replace("/", "_") or "_root"}.log'
            procs[ns] = self._launch(f'{robot}_app bringup.launch.py mode:=mock rviz:=false',
                                     logs[ns])
        probe = None
        try:
            for ns, robot, p in CELLS:
                ok = _wait_log(logs[ns], r'You can start planning now', 120)
                ok2 = _wait_log(logs[ns], r'trainit_mock adapter for ', 60)
                self.obs[ns]['ready'] = ok and ok2
                self.say(f'[{ns or "/"}] bring-up: move_group ready {ok}, adapter up {ok2}')
            probe = self._probe('t13_probe')
            self._probe_cells(probe, logs)
        finally:
            if probe is not None:
                probe.close()
            self._stop_all(procs, 'A')
        self._judge_a()

    def _probe_cells(self, probe: '_Probe', logs: dict) -> None:
        import rclpy
        from builtin_interfaces.msg import Duration as MsgDuration
        from control_msgs.action import FollowJointTrajectory, GripperCommand
        from control_msgs.msg import JointTolerance
        from controller_manager_msgs.srv import ListControllers
        from moveit_msgs.action import ExecuteTrajectory
        from moveit_msgs.msg import (Constraints, JointConstraint, MotionPlanRequest,
                                     PlanningSceneComponents)
        from moveit_msgs.srv import GetMotionPlan, GetPlanningScene
        from rclpy.action import ActionClient
        from rclpy.duration import Duration
        from rclpy.qos import DurabilityPolicy, QoSProfile, ReliabilityPolicy
        from sensor_msgs.msg import JointState
        from std_srvs.srv import SetBool
        from tf2_ros import Buffer, TransformListener
        from trainit_interfaces.msg import EndEffectorState
        from trajectory_msgs.msg import JointTrajectoryPoint

        node = probe.node
        tfbuf = Buffer()
        probe.tf_listener = TransformListener(tfbuf, node, spin_thread=False)
        js = {ns: {} for ns, _r, _p in CELLS}        # ns -> {name tuple: last positions}
        eef = {}

        def on_js(ns):
            def cb(msg):
                js[ns][tuple(msg.name)] = list(msg.position)
            return cb

        def on_eef(ns):
            def cb(msg):
                eef[ns] = msg
            return cb
        latched = QoSProfile(depth=1, reliability=ReliabilityPolicy.RELIABLE,
                             durability=DurabilityPolicy.TRANSIENT_LOCAL)
        for ns, _r, _p in CELLS:
            node.create_subscription(JointState, f'{ns}/joint_states', on_js(ns), 50)
            node.create_subscription(EndEffectorState, f'{ns}/eef/{DEV}/state', on_eef(ns),
                                     latched)

        def call(srv_type, name, req, timeout=30.0):
            cli = node.create_client(srv_type, name)
            try:
                if not cli.wait_for_service(timeout_sec=timeout):
                    return None
                fut = cli.call_async(req)
                end = time.monotonic() + timeout
                while not fut.done() and time.monotonic() < end:
                    time.sleep(0.05)
                return fut.result() if fut.done() else None
            finally:
                node.destroy_client(cli)

        def send_goal(action_type, name, goal, timeout=30.0):
            ac = ActionClient(node, action_type, name)
            try:
                if not ac.wait_for_server(timeout_sec=timeout):
                    return 'NO SERVER', None
                gf = ac.send_goal_async(goal)
                end = time.monotonic() + timeout
                while not gf.done() and time.monotonic() < end:
                    time.sleep(0.05)
                gh = gf.result()
                if gh is None or not gh.accepted:
                    return 'REJECTED', None
                rf = gh.get_result_async()
                while not rf.done() and time.monotonic() < end:
                    time.sleep(0.05)
                if not rf.done():
                    return 'TIMEOUT', None
                return ({4: 'SUCCEEDED', 5: 'CANCELED', 6: 'ABORTED'}.get(
                    rf.result().status, str(rf.result().status)), rf.result().result)
            finally:
                ac.destroy()

        def fjt(ns, actuator, joint, value):
            g = FollowJointTrajectory.Goal()
            g.trajectory.joint_names = [joint]
            g.trajectory.points = [JointTrajectoryPoint(
                positions=[value], time_from_start=MsgDuration(sec=1, nanosec=0))]
            g.goal_tolerance = [JointTolerance(name=joint, position=0.01)]
            g.goal_time_tolerance = MsgDuration(sec=0, nanosec=500_000_000)
            return send_goal(FollowJointTrajectory,
                             f'{ns}/{actuator}_controller/follow_joint_trajectory', g)[0]

        def latest(ns, joint):
            for names, pos in js[ns].items():
                if joint in names:
                    return pos[names.index(joint)]
            return None

        def tf(target, source):
            try:
                t = tfbuf.lookup_transform(target, source, rclpy.time.Time(),
                                           timeout=Duration(seconds=3.0))
                v = t.transform.translation
                return (round(v.x, 3), round(v.y, 3), round(v.z, 3))
            except Exception as exc:          # noqa: BLE001
                return f'FAILED ({type(exc).__name__})'

        def scene_joint(ns, joint):
            req = GetPlanningScene.Request()
            req.components.components = PlanningSceneComponents.ROBOT_STATE
            got = call(GetPlanningScene, f'{ns}/get_planning_scene', req)
            if got is None:
                return 'NO SERVICE'
            st = got.scene.robot_state.joint_state
            return (round(st.position[list(st.name).index(joint)], 3) if joint in st.name
                    else 'ABSENT')

        def commands(msg):          # actuator -> (last_command, last_command_stamp)
            return ({} if msg is None else
                    {a.actuator: (a.last_command, a.last_command_stamp.sec,
                                  a.last_command_stamp.nanosec) for a in msg.actuators})

        def commanded(ns, label, actuator, send):
            """K5: send ONE command, then wait for the commanded actuator's last_command / stamp
            to move, and record which actuators moved (only that one may)."""
            before = commands(eef.get(ns))
            result = send()
            end = time.monotonic() + 5.0
            after = commands(eef.get(ns))
            while time.monotonic() < end and after.get(actuator) == before.get(actuator):
                time.sleep(0.05)
                after = commands(eef.get(ns))
            moved = sorted(a for a in set(before) | set(after) if before.get(a) != after.get(a))
            self.obs[ns].setdefault('deltas', []).append((label, actuator, moved))
            return result

