def _task_header(task, plan: ProgramPlan) -> List[str]:
    """A task's description and data (vNext M3.7), when it has them, above its steps."""
    out = []
    if task.description:
        out += [task.description, '']
    if task.inputs or task.outputs:
        takes = ', '.join(d.describe() for d in task.inputs) or 'nothing'
        gives = ', '.join(d.describe() for d in task.outputs) or 'nothing'
        out += [f'Takes {takes}; gives {gives} (by name, on the application\'s one blackboard).', '']
    if task.name not in plan.running:
        out += ['(This task never runs: neither the main task nor a task it runs calls it.)', '']
    return out


def _body_range(body) -> str:
    first, last = body[0].label, body[-1].label
    return f'step {first}' if first == last else f'steps {first}-{last}'


def _step_rows(task, steps, plan: ProgramPlan) -> List[str]:
    """One table row per step, the steps of a control body below it with their labels (3.1, 3.2.1)."""
    out: List[str] = []
    for sp in steps:
        i = sp.label
        if sp.kind == 'move':
            mp = sp.move
            entry = plan.move_entries[(task.name, mp.step)]
            target = f'`{mp.waypoint}`' + (f' (entry `{entry}`)' if entry != mp.waypoint else '')
            out.append(f'| {i} | move {mp.motion.upper()} | {target} | '
                       f'{move_text(mp, with_motion=False)} | '
                       f'{_pct(mp.speed)} / {_pct(mp.accel)} |')
        elif sp.kind == 'path':
            pp = next((p for p in plan.paths if p.name == sp.path), None)
            res = pp.resolution
            v, a = res.velocity_scaling, res.acceleration_scaling
            limits = (f'{_pct(percent(v.value))} / {_pct(percent(a.value))}' if v and a
                      else 'per segment')
            how = f'ONE motion, {provider_text(res)}'
            if pp.events:
                runs = sum(1 for n in sp.nodes if n.startswith('<FollowPath'))
                how += (f'; it stops for {len(pp.events)} process event(s): {runs} run(s) of the '
                        'path with the events between them')
            out.append(f'| {i} | path | `{sp.path}` | {how} | {limits} |')
        elif sp.kind == 'process':
            ev = sp.event
            key = f' -> `{sp.captures[0][0]}`' if sp.captures else ''
            out.append(f'| {i} | process | -- | {ev.describe()}{key} (where the robot is) | -- |')
        elif sp.kind == 'task':        # vNext M3.7
            out.append(f'| {i} | task | `{sp.call}` | calls task `{sp.call}`: its steps run, then the next '
                       'step | -- |')
        elif sp.kind == 'repeat':
            times = ('until a step fails or the program is stopped' if sp.count == -1 else
                     f'{sp.count} cycle' + ('' if sp.count == 1 else 's'))
            out.append(f'| {i} | repeat | -- | {_body_range(sp.bodies[0])}, {times}; a step that fails ends '
                       'the repeat | -- |')
        elif sp.kind == 'retry':
            out.append(f'| {i} | retry | -- | {_body_range(sp.bodies[0])}, again from the first when one fails: '
                       f'{sp.count} tr' + ('y' if sp.count == 1 else 'ies') + ' at most | -- |')
        elif sp.kind == 'fallback':
            alts = '; '.join(f'{_body_range(b)}' for b in sp.bodies)
            out.append(f'| {i} | fallback | -- | {len(sp.bodies)} alternatives, in order, until one succeeds: '
                       f'{alts} | -- |')
        elif sp.summary is not None:   # vNext M3.6: detect, grasp, release, tool
            target, how, limits = sp.summary
            out.append(f'| {i} | {sp.kind} | {target} | {how} | {limits} |')
        else:
            out.append(f'| {i} | dwell | -- | hold {sp.dwell_ms} ms | -- |')
        for body in sp.bodies:
            out += _step_rows(task, body, plan)
    return out


TASKS_HEADER = """\
# The application's TASKS (tasks.yaml schema 1), generated by the TrainIt Setup Assistant from the
# project's Canonical Task Program: a MANIFEST -- each task's stable name, its BehaviorTree (in
# bt_trees/task_program.xml), and the data it takes and gives -- for a reader and for a later task
# server. Nothing reads it to run the program: trainit_run_bt runs bt_params.yaml's bt_tree_id
# (MainTree), which runs main_task's tree, and a task calls another with <SubTree ID="task_<name>">.
# A task's inputs and outputs are data on the application's one blackboard, by name: a candidate set
# (a detect step's out) or a capture (a capture's out).
"""


def _data_flow(items) -> str:
    return '[' + ', '.join(f'{{name: {d.name}, type: {d.type.value}}}' for d in items) + ']'


def tasks_yaml(project, plan: ProgramPlan) -> str:
    """config/tasks.yaml: the task manifest (M3_SCHEMA_PROPOSAL §2.3), in declaration order."""
    lines = [TASKS_HEADER.rstrip('\n'), 'schema_version: 1', f'main_task: {plan.main_task}', 'tasks:']
    for task in project.application.program.tasks:
        lines.append(f'  {task.name}:')
        lines.append(f'    tree: {task_tree_id(task.name)}')
        if task.description:
            lines.append(f'    description: {json.dumps(task.description)}')
        lines.append(f'    inputs: {_data_flow(task.inputs)}')
        lines.append(f'    outputs: {_data_flow(task.outputs)}')
    return '\n'.join(lines) + '\n'


def _events(plan: ProgramPlan):
    """Every process event of the plan: the process steps', then the paths'."""
    out = [sp.event for steps in plan.tasks.values() for sp in iter_plans(steps) if sp.event is not None]
    return out + [e.event for pp in plan.paths for e in pp.events]


def _path_limits(pp) -> str:
    """A path's profile, its scalings (with a TCP derivation) and its goal tolerance."""
    d = pp.data
    parts = [f'profile {d["profile"]}']
    if 'velocity_scaling' in d:
        parts.append(f'{_pct(percent(d["velocity_scaling"]))} / '
                     f'{_pct(percent(d["acceleration_scaling"]))}')
    parts += scaling_text(pp.resolution)
    if 'goal_tolerance' in d:
        g = d['goal_tolerance']
        parts.append(f'goal tolerance {fmtnum(g["position_m"])} m, {fmtnum(g["orientation_rad"])} rad')
    return '; '.join(parts)


def _plain(value):
    if hasattr(value, 'requested') or hasattr(value, '__fields__'):
        names = list(getattr(type(value), 'model_fields', None) or type(value).__fields__)
        return {n: getattr(value, n) for n in names if getattr(value, n) is not None}
    return value


def _limits_text(plan: ProgramPlan) -> str:
    if plan.limits is None:
        return 'not used here'
    return (f'max_trans_vel {fmtnum(plan.limits.max_trans_vel)} m/s, max_trans_acc '
            f'{fmtnum(plan.limits.max_trans_acc)} m/s^2, from {plan.limits.source}')


