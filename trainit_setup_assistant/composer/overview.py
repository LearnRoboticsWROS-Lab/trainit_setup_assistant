"""The Project Overview (vNext I0.1, I0_DESIGN.md §18): one line per block, with a status mark.

The overview is READ from the project, its validation and its scene-sync status. Nothing in it is
stored, and the generation state is read from an output directory's manifest. It is pure data; the
Qt panel only renders it.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import List, Optional, Sequence

from ..model.project import CanonicalProject
from .integration import CURRENT, MANUAL, STALE, STATEMENT, SceneStatus
from .ops import step_kind, walk

OK, WARN, ERROR, INFO = 'ok', 'warn', 'error', 'info'


@dataclass(frozen=True)
class OverviewRow:
    block: str                  # ROBOT, MOVEIT CONFIG, DEPLOYMENT, WORLD, ...
    text: str
    mark: str = INFO            # ok | warn | error | info
    detail: str = ''            # progressive disclosure: the tooltip / expanded text


def _with_code(lines: Sequence[str], code: str) -> List[str]:
    return [line for line in lines if line.startswith(code)]


def process_channels(project: CanonicalProject) -> List[str]:
    """The LOGICAL process channels a task program uses, in first-use order (derived, read-only)."""
    app = project.application
    if not app.is_task_program():
        return []
    from ..model.io import program_as_written
    doc = program_as_written(app.program)
    out: List[str] = []

    def add(node):
        ch = node.get('channel') if isinstance(node, dict) else None
        if ch and ch not in out:
            out.append(ch)
    for path in doc.get('paths') or []:
        for ev in path.get('events') or []:
            add(ev)
    for task in doc.get('tasks') or []:
        for _label, step in walk(task.get('steps') or []):
            if step_kind(step) == 'process':
                add(step['process'])
    return out


def _generation(generation_dir) -> Optional[OverviewRow]:
    if not generation_dir:
        return None
    manifest = Path(generation_dir) / 'generation_manifest.yaml'
    if not manifest.is_file():
        return OverviewRow('GENERATION', f'not generated yet into {generation_dir}', INFO)
    import yaml
    try:
        data = yaml.safe_load(manifest.read_text()) or {}
    except Exception:  # noqa: BLE001 - an unreadable manifest is shown, not raised
        return OverviewRow('GENERATION', f'{generation_dir}: unreadable manifest', WARN)
    version = (data.get('provenance') or {}).get('generator_version') or data.get('generator_version', '?')
    return OverviewRow('GENERATION', f'{generation_dir} · TSA {version} · {data.get("file_count", "?")} files',
                       OK)


def project_overview(project: CanonicalProject, status: SceneStatus, errors: Sequence[str] = (),
                     warnings: Sequence[str] = (), generation_dir=None) -> List[OverviewRow]:
    """The overview rows of a project whose paths are resolved."""
    r = project.robot
    rows: List[OverviewRow] = []
    rows.append(OverviewRow(
        'ROBOT', f'{r.robot_name} · group {r.planning_group.name} · {r.planning_group.base_link} → '
                 f'{r.planning_group.tip_link} · {len(r.planning_group.joints)} joints', OK))
    drift = _with_code(warnings, 'R-I0-01')
    if r.base_moveit_config_path:
        rows.append(OverviewRow(
            'MOVEIT CONFIG', f'{r.base_moveit_config_package or Path(r.base_moveit_config_path).name} '
                             f'(the robot planning authority)' + (' · DRIFT' if drift else ''),
            WARN if drift else OK, '\n'.join(drift) or f'{r.base_moveit_config_path}'))
    else:
        rows.append(OverviewRow(
            'MOVEIT CONFIG', 'none: a quick robot generated by TSA (samples / education); a real cell '
                             'uses a MoveIt config made with MoveIt Setup Assistant', INFO))
    dep = project.deployment
    modes = ', '.join(getattr(m, 'value', m) for m in dep.modes)
    rows.append(OverviewRow('DEPLOYMENT', f'modes {modes} · default {getattr(dep.default_mode, "value", dep.default_mode)}',
                            OK))
    prov = project.scene.provenance
    world_mark = {CURRENT: OK, STALE: WARN, MANUAL: INFO}.get(status.world, INFO)
    if prov is not None:
        world_text = f'{prov.source.replace("_", " ")} {prov.file} · {status.world}'
    elif dep.isaac is not None:
        world_text = f'isaac stage {dep.isaac.stage} · scene not imported from it ({MANUAL})'
    elif project.scene.world_path:
        world_text = f'gazebo world {project.scene.world_path} · {status.world}'
    else:
        world_text = f'no deployment world: the scene is authored in the project ({MANUAL})'
    rows.append(OverviewRow('WORLD', world_text, world_mark, status.world_detail))
    b_err, b_warn = _with_code(errors, 'R-I0-02'), _with_code(warnings, 'R-I0-02')
    if dep.isaac is not None:
        rows.append(OverviewRow(
            'ROBOT BINDING', f'robot prim {dep.isaac.robot_prim or "(none)"} in the Isaac stage',
            ERROR if b_err else WARN if b_warn else OK, '\n'.join(b_err + b_warn) or
            'joints matched by name; the base frame found in the stage'))
    elif project.scene.world_path:
        pose = project.scene.robot_base_world_pose or [0.0] * 6
        rows.append(OverviewRow('ROBOT BINDING', f'the robot is spawned into the gazebo world at {pose}', INFO))
    else:
        rows.append(OverviewRow('ROBOT BINDING', 'none: '
                                + ('no Isaac world is bound' if b_warn else 'no deployment world'),
                                WARN if b_warn else INFO, '\n'.join(b_warn)))
    counts = {}
    for o in status.objects:
        counts[o.category] = counts.get(o.category, 0) + 1
    rows.append(OverviewRow(
        'SCENE', ' · '.join(f'{n} {cat}' for cat, n in sorted(counts.items())) or 'no objects',
        WARN if status.world == STALE else OK if counts else INFO,
        '\n'.join(f'{o.id} ({o.category}): {o.status} — {o.detail}' for o in status.objects)))
    rows.append(OverviewRow('SCENE SYNC', status.header(), INFO, STATEMENT))
    rows.append(_tools(project))
    rows.append(_sensors(project))
    app = project.application
    if app.is_task_program():
        prog = app.program
        rows.append(OverviewRow(
            'APPLICATION', f'{len(prog.waypoints)} waypoints · {len(prog.paths)} paths · '
                           f'{len(prog.motion_profiles)} profiles · {len(prog.tasks)} tasks · main '
                           f'{prog.main_task}', OK))
        channels = process_channels(project)
        rows.append(OverviewRow('PROCESS CHANNELS', ', '.join(channels) or 'none',
                                INFO, 'logical ids, derived from the process steps and path events'))
    else:
        rows.append(OverviewRow('APPLICATION', f'template application {app.type.value}', INFO))
    if errors:
        rows.append(OverviewRow('VALIDATION', f'{len(errors)} error(s), {len(warnings)} warning(s)', ERROR,
                                '\n'.join(list(errors) + list(warnings))))
    elif warnings:
        rows.append(OverviewRow('VALIDATION', f'valid · {len(warnings)} warning(s)', WARN, '\n'.join(warnings)))
    else:
        rows.append(OverviewRow('VALIDATION', 'valid', OK))
    gen = _generation(generation_dir)
    if gen is not None:
        rows.append(gen)
    return rows


def _tools(project: CanonicalProject) -> OverviewRow:
    g = project.robot.gripper
    if g.contract is None:
        kind = getattr(g.kind, 'value', g.kind)
        return OverviewRow('TOOLS / EEF', f'{kind} gripper' + (f' ({g.eef_name})' if g.eef_name else ''), INFO)
    try:
        from ..model.end_effector import derive_device
        dev = derive_device(g, project.robot.named_states)
        acts = ', '.join(a.id for a in dev.actuators)
        sites = ', '.join(s.id for s in dev.sites)
        return OverviewRow('TOOLS / EEF', f'{dev.id} · actuators {acts or "none"} · sites {sites or "none"}', OK)
    except Exception as exc:  # noqa: BLE001 - shown, never raised
        return OverviewRow('TOOLS / EEF', f'{g.contract.id} (contract)', WARN, str(exc))


def _sensors(project: CanonicalProject) -> OverviewRow:
    per = project.perception
    if per is None:
        return OverviewRow('SENSORS', 'none', INFO)
    detectors = ', '.join(d.name for d in per.detectors) or 'no detector'
    cam = per.camera
    cam_text = f'camera {cam.rgb_topic}' if cam is not None and getattr(cam, 'rgb_topic', None) else 'no camera'
    return OverviewRow('SENSORS', f'{cam_text} · detectors {detectors}', OK)


__all__ = ['ERROR', 'INFO', 'OK', 'OverviewRow', 'WARN', 'process_channels', 'project_overview']
