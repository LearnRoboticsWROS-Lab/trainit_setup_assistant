    def _graph(self, probe: '_Probe') -> None:
        """K4's node and topic rule, on the graph of the three cells (recorded, printed later)."""
        node = probe.node
        by_ns = {}
        for ns, n in probe.nodes():
            by_ns.setdefault(ns, []).append(n)
        cells = {ns or '/' for ns, _r, _p in CELLS}
        outside_cells = sorted(set(by_ns) - cells)
        names = {ns: sorted(_stable(n) for n in by_ns.get(ns, [])) for ns in sorted(cells)}
        same = len({tuple(v) for v in names.values()}) == 1 and bool(names['/'])
        escaped = {}
        for ns in sorted(cells - {'/'}):
            out = []
            for n in sorted(by_ns.get(ns, [])):
                try:
                    pubs = node.get_publisher_names_and_types_by_node(n, ns)
                    srvs = node.get_service_names_and_types_by_node(n, ns)
                except Exception as exc:          # noqa: BLE001 -- a node gone since the listing
                    out.append(f'{ns}/{_stable(n)} could not be queried ({type(exc).__name__})')
                    continue
                out += [f'{ns}/{_stable(n)} publishes {t}' for t, _t in pubs
                        if not t.startswith(ns + '/') and t not in GRAPH_EXEMPT]
                out += [f'{ns}/{_stable(n)} serves {s}' for s, _t in srvs
                        if not s.startswith(ns + '/')]
            escaped[ns] = sorted(out)
        lines = [f'[+K4 graph] nodes per namespace: {names}',
                 f'[+K4 graph] the three cells hold the same node names: {same}',
                 f'[+K4 graph] other namespaces holding a node: {outside_cells or "(none)"}']
        for ns, out in escaped.items():
            lines.append(f'[+K4 graph] {ns}: names provided outside {ns} (except '
                         f'{" ".join(GRAPH_EXEMPT)}): {out or "(none)"}')
        self.obs['']['graph_lines'] = lines
        self.obs['']['graph_ok'] = same and not outside_cells and not any(escaped.values())

