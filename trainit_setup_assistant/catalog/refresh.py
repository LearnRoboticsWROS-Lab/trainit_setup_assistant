"""Refresh TSA's catalog from the installed workspace: the ONE explicit maintenance step (ADR-0021).

    python3 -m trainit_setup_assistant.catalog.refresh            # write the files
    python3 -m trainit_setup_assistant.catalog.refresh --check    # compare only; exit 1 on drift

Run it with the system ``python3`` after sourcing ``/opt/ros/humble/setup.bash`` and the
workspace's ``install/setup.bash``: it reads the trainit_motion_runtime and trainit_perception the
workspace INSTALLS. Three files, all or none:

  tmr_planner_registry.yaml   a byte copy of TMR's planner registry (vNext M2.1)
  tp_registry_snapshot.yaml   trainit_perception's configuration vocabulary (vNext M2.2)
  snapshot.yaml               the catalog derived from both, recording their sha256

1. READ      TMR's installed planner registry and ``trainit_perception.vocabulary.export()``;
2. VALIDATE  each against the schema this TSA reads and the tokens TSA's own code names; TP's
             record also for a Community/Pro classification of every method, rule and face
             (``TP_TIERS``, an owner decision), and its release against the one an installed
             ``package.xml`` on the ament index declares (no such package.xml, or another
             release, is refused);
3. COMPARE   TP's vocabulary with the committed snapshot, entry by entry and in order (the drift
             report): a method, rule, face or term the snapshot has and TP no longer exports is
             REFUSED -- committed projects persist those tokens and would stop loading. A
             committed snapshot that cannot be read, or that was changed outside the refresh (its
             sha256 is not the one ``snapshot.yaml`` records), is replaced whole -- the removals
             are then judged against the names ``snapshot.yaml`` records;
4. DERIVE    ``snapshot.yaml``, in a CHILD interpreter whose catalog readers answer with the
             candidates: the caller never imports a model built from a vocabulary that may not be
             written, so a --check, a refusal or a failure leaves nothing behind in the process;
5. WRITE     the three files, built in memory first, then replaced together: temporary files
             beside them (never ``*.yaml``, so a crash leaves nothing a package would ship), the
             existing file mode kept, ``snapshot.yaml`` -- which records the other two -- last,
             and every file already replaced put back if a later one fails.

Any refusal is exit 2 with nothing written; ``--check`` runs 1-4, prints the drift and writes
nothing. Generation never runs this: it reads what was committed.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Dict, List, Optional, Tuple

from . import (REFRESH, REGISTRY_FILE, TP_REGISTRY_FILE, missing_required_modes,
               parse_planner_registry, parse_tp_registry, tp_drift, tp_registry_text,
               tp_tier_problems, tp_vocabulary_problems)

SNAPSHOT_FILE = 'snapshot.yaml'
HEADER = (
    '# GENERATED by trainit_setup_assistant.catalog.refresh (derive.derive()) -- '
    'do not edit by hand.\n'
    "# What TrainIt HAS, read from the registries that own each fact (TSA enums, TMR's\n"
    "# installed planner registry, TP's installed registries, MoveIt's installed packages).\n"
    '# test_catalog.py fails when a registry moves and this file does not (vNext M1, M2.1).\n')
# what a removal of these means for a committed project: it would no longer load
_PERSISTED = ('detector_methods', 'rules', 'terms', 'faces')
_TMP_SUFFIX = '.refresh-tmp'


class Refused(RuntimeError):
    """The installed workspace cannot be turned into a catalog this TSA can read."""


def catalog_dir() -> Path:
    return Path(__file__).resolve().parent


def tmr_registry_path() -> Path:
    """TMR's INSTALLED planner registry. A catalog refreshed without it would be wrong."""
    try:
        from ament_index_python.packages import get_package_share_directory
        share = Path(get_package_share_directory('trainit_motion_runtime'))
    except Exception as exc:                                    # noqa: BLE001
        raise Refused('trainit_motion_runtime is not installed or the workspace is not sourced '
                      f'(source /opt/ros/humble/setup.bash and install/setup.bash): {exc}') from exc
    path = share / 'config' / 'planner_profiles.yaml'
    if not path.is_file():
        raise Refused(f'the installed trainit_motion_runtime ships no planner registry ({path}): '
                      'it predates TMR 1.8.0 -- rebuild and re-source the workspace')
    return path


def tp_available() -> bool:
    """trainit_perception's vocabulary is importable -- what the refresh reads it through."""
    try:
        import trainit_perception.vocabulary  # noqa: F401
        return True
    except Exception:                                           # noqa: BLE001
        return False


_NOT_IMPORTABLE = ('trainit_perception is not importable here, so its vocabulary cannot be read: '
                   'source the workspace that installs it (trainit_perception 0.5.0 or newer, '
                   'which exports it)')


def tp_export() -> dict:
    """trainit_perception's INSTALLED configuration vocabulary (``vocabulary.export()``)."""
    try:
        from trainit_perception.vocabulary import export
    except Exception as exc:                                    # noqa: BLE001
        raise Refused(f'{_NOT_IMPORTABLE}: {exc}') from exc
    try:
        return export()
    except ValueError as exc:
        raise Refused(f'trainit_perception refuses its own vocabulary: {exc}') from exc
    except Exception as exc:                                    # noqa: BLE001 - a broken TP
        raise Refused(f'trainit_perception.vocabulary.export() failed '
                      f'({type(exc).__name__}: {exc})') from exc


def tp_installed_release() -> Optional[str]:
    """The release an installed trainit_perception ``package.xml`` on the ament index declares.

    Raises Refused when there is none to read -- not on the index, or a package.xml that cannot be
    read or names no release -- saying which, and where TP was imported from."""
    import xml.etree.ElementTree as ET
    try:
        import trainit_perception
        imported = getattr(trainit_perception, '__file__', None) or '?'
    except Exception:                                           # noqa: BLE001
        imported = 'nowhere'
    try:
        from ament_index_python.packages import get_package_share_directory
        xml = Path(get_package_share_directory('trainit_perception')) / 'package.xml'
    except Exception as exc:                                    # noqa: BLE001
        raise Refused(f'trainit_perception (imported from {imported}) is not on the ament index '
                      f'({type(exc).__name__}), so no installed package.xml confirms the release '
                      'the snapshot would name: source the workspace install that provides it')
    try:
        release = ET.parse(xml).getroot().findtext('version')
    except Exception as exc:                                    # noqa: BLE001
        raise Refused(f'the installed {xml} cannot be read ({type(exc).__name__}): rebuild the '
                      'workspace')
    if not release:
        raise Refused(f'the installed {xml} names no <version>: rebuild the workspace')
    return release.strip()


_CHILD = r'''
import json, sys
from pathlib import Path
import trainit_setup_assistant.catalog as C
work = Path(sys.argv[1])
registry_bytes = (work / 'tmr.yaml').read_bytes()
registry = C.parse_planner_registry(registry_bytes, 'the candidate TMR registry')
record = C.parse_tp_registry((work / 'tp.yaml').read_bytes(), 'the candidate TP vocabulary')
# The catalog's readers answer with the candidates BEFORE the model is first imported, so the
# model this interpreter builds is the one about to be written -- even when a committed file is
# broken -- and it dies with this interpreter.
C._registry_copy = lambda: registry
C._tp_snapshot = lambda: record
from trainit_setup_assistant.catalog.derive import derive
(work / 'record.json').write_text(json.dumps(derive(tmr_bytes=registry_bytes,
                                                    tp_vocabulary=record)))
'''


def derive_record(tmr_bytes: Optional[bytes] = None, tp_vocabulary: Optional[dict] = None) -> dict:
    """The catalog record ``derive()`` makes of these inputs, computed in a CHILD interpreter.

    ``derive()`` imports TSA's model, and the model builds its vocabulary when it is imported: in
    the caller that would be a model built from a vocabulary that may never be written, which no
    module purge can undo (pydantic 1.x refuses to declare a validator twice in one process). In a
    child it is built from the candidates and dies with the child."""
    if tmr_bytes is None:
        tmr_bytes = tmr_registry_path().read_bytes()
    if tp_vocabulary is None:
        tp_vocabulary = tp_export()
    work = Path(tempfile.mkdtemp(prefix='tsa_catalog_refresh_'))
    try:
        (work / 'tmr.yaml').write_bytes(tmr_bytes)
        (work / 'tp.yaml').write_text(tp_registry_text(tp_vocabulary))
        root = str(Path(__file__).resolve().parents[2])        # the dir holding this package
        env = dict(os.environ, PYTHONDONTWRITEBYTECODE='1',
                   PYTHONPATH=os.pathsep.join(p for p in (root, os.environ.get('PYTHONPATH'))
                                              if p))
        r = subprocess.run([sys.executable, '-c', _CHILD, str(work)], capture_output=True,
                           text=True, env=env, cwd=str(work))
        if r.returncode != 0:
            last = (r.stderr.strip().splitlines() or [f'exit {r.returncode}'])[-1]
            raise RuntimeError(f'derive failed in its child interpreter: {last}')
        return json.loads((work / 'record.json').read_text())
    finally:
        shutil.rmtree(work, ignore_errors=True)


def snapshot_text(record: dict) -> str:
    import yaml
    return HEADER + yaml.safe_dump(record, sort_keys=False, width=100)


def _read(path: Path) -> Optional[bytes]:
    return path.read_bytes() if path.is_file() else None


def _validate_registry(data: bytes, where: str) -> dict:
    try:
        registry = parse_planner_registry(data, where)
        missing = missing_required_modes(registry)
    except RuntimeError as exc:
        raise Refused(str(exc)) from exc
    except Exception as exc:                                    # noqa: BLE001 - a broken registry
        raise Refused(f'{where} is not a planner registry this TSA can read '
                      f'({type(exc).__name__}: {exc})') from exc
    if missing:
        raise Refused(f'{where} no longer offers {missing}, which TSA\'s own code names (the '
                      'default planner of a project file, the D-016 vision rule): change TSA '
                      'first, then refresh')
    return registry


def _validate_tp(record: dict) -> Tuple[dict, bytes]:
    """TP's record, held to everything this TSA reads it for; its canonical bytes."""
    where = 'trainit_perception.vocabulary.export()'
    try:
        text = tp_registry_text(record).encode()
        parsed = parse_tp_registry(text, where)
    except RuntimeError as exc:
        raise Refused(str(exc)) from exc
    except Exception as exc:                                    # noqa: BLE001 - not plain data
        raise Refused(f'{where} is not plain data ({type(exc).__name__}: {exc})') from exc
    if parsed != record:
        raise Refused(f'{where} is not plain data: it does not survive its own canonical YAML')
    problems = tp_vocabulary_problems(record) + tp_tier_problems(record)
    if problems:
        raise Refused('; '.join(problems) + ' -- change TSA (or classify the entry) first, then '
                      'refresh')
    installed = tp_installed_release()                          # raises its own Refused
    if installed != record['trainit_perception']:
        raise Refused(f'the imported trainit_perception says {record["trainit_perception"]} and '
                      f'its installed package.xml says {installed}: rebuild or re-source the '
                      'workspace')
    return record, text


def _recorded(here: Path) -> Optional[dict]:
    """What the committed ``snapshot.yaml`` records of trainit_perception, or None."""
    import yaml
    try:
        record = yaml.safe_load(_read(here / SNAPSHOT_FILE) or b'') or {}
        return record['registries']['trainit_perception']
    except Exception:                                           # noqa: BLE001 - absent/unreadable
        return None


def _baseline(here: Path) -> Tuple[Optional[dict], Optional[dict], Optional[str]]:
    """(what removals are judged against, the committed TP snapshot to report drift against, why
    it cannot be used). The committed snapshot, when it is readable and the one ``snapshot.yaml``
    records; otherwise the names ``snapshot.yaml`` records -- and the reason."""
    data = _read(here / TP_REGISTRY_FILE)
    recorded = _recorded(here)
    names = None
    if recorded:
        names = {'detector_methods': dict.fromkeys(list(recorded.get('in_process_methods') or [])
                                                   + list(recorded.get('external_methods') or [])),
                 'rules': dict.fromkeys(recorded.get('rules') or []),
                 'faces': dict.fromkeys(recorded.get('faces') or [])}
    if data is None:
        return names, None, 'TSA has no snapshot of trainit_perception\'s vocabulary yet'
    try:
        committed = parse_tp_registry(data, f'catalog/{TP_REGISTRY_FILE}')
    except RuntimeError as exc:
        return names, None, f'TSA snapshot unreadable -- {exc}; the refresh replaces it whole'
    sha = ((recorded or {}).get('vocabulary') or {}).get('sha256')
    if sha and hashlib.sha256(data).hexdigest() != sha:
        return names, None, ('TSA snapshot was changed outside the refresh (its sha256 is not the '
                             'one snapshot.yaml records): the refresh replaces it whole -- restore '
                             'it with git if the change was not meant')
    return committed, committed, None


def _removals(old: Optional[dict], new: dict) -> List[str]:
    if old is None:
        return []
    return [f'{section} {name!r}' for section in _PERSISTED for name in old.get(section) or {}
            if name not in new[section]]


def _reread_catalog() -> None:
    """The cached catalog readers forget what they read, and so does a face registry built from
    them -- lazily: the next reader in this process reads the files as they are then."""
    from .. import catalog as C
    C._registry_copy.cache_clear()
    C._tp_snapshot.cache_clear()
    faces = sys.modules.get('trainit_setup_assistant.model.faces')
    if faces is not None:
        faces._cache = None


def build(check: bool) -> Tuple[Dict[str, bytes], List[str]]:
    """READ, VALIDATE, COMPARE, DERIVE: the three files' bytes -- nothing written. Raises Refused."""
    here = catalog_dir()
    source = tmr_registry_path()
    try:
        registry = source.read_bytes()
    except OSError as exc:
        raise Refused(f'{source} cannot be read: {exc}') from exc
    _validate_registry(registry, str(source))
    if not check and not tp_available():
        raise Refused(_NOT_IMPORTABLE)
    record, tp_text = _validate_tp(tp_export())
    baseline, committed, why = _baseline(here)
    report = []
    if why:
        report.append(f'TP registry drift: {why}')
    elif _read(here / TP_REGISTRY_FILE) != tp_text:
        report = tp_drift(committed, record) or [
            'TP registry drift: TSA snapshot is not the canonical text of TP\'s vocabulary']
    if baseline is None and _read(here / TP_REGISTRY_FILE) is not None and not check:
        raise Refused(f'{why}; and snapshot.yaml records no vocabulary either, so the removals '
                      'cannot be judged: restore both files with git, then refresh')
    gone = _removals(baseline, record)
    if gone:
        raise Refused(f'TP no longer exports {", ".join(gone)}, which TSA\'s snapshot has and '
                      'committed projects may hold (they would stop loading): a removal needs '
                      'TSA to migrate those projects first')
    try:
        snapshot = snapshot_text(derive_record(tmr_bytes=registry, tp_vocabulary=record)).encode()
    except Refused:
        raise
    except Exception as exc:                                    # noqa: BLE001
        raise Refused(f'the catalog could not be derived ({type(exc).__name__}: {exc})') from exc
    return {REGISTRY_FILE: registry, TP_REGISTRY_FILE: tp_text, SNAPSHOT_FILE: snapshot}, report


def _write_all(here: Path, files: Dict[str, bytes]) -> None:
    """Replace ``files`` (in order; the last one records the others) as a set, or none of them."""
    staged: List[Tuple[Path, Path, Optional[bytes]]] = []
    try:
        for name, data in files.items():
            target = here / name
            tmp = here / f'.{name}{_TMP_SUFFIX}'
            tmp.write_bytes(data)
            os.chmod(tmp, (target.stat().st_mode & 0o777) if target.exists() else 0o644)
            staged.append((tmp, target, _read(target)))
        done: List[Tuple[Path, Optional[bytes]]] = []
        try:
            for tmp, target, before in staged:
                os.replace(tmp, target)
                done.append((target, before))
        except BaseException:
            for target, before in reversed(done):
                if before is None:
                    target.unlink()
                else:
                    target.write_bytes(before)
            raise
    finally:
        for tmp, _, _ in staged:
            if tmp.exists():
                tmp.unlink()


def refresh(check: bool) -> List[str]:
    """What drifted (written unless `check`). Raises Refused, having written nothing."""
    drift, _ = refresh_with_report(check)
    return drift


def refresh_with_report(check: bool) -> Tuple[List[str], List[str]]:
    here = catalog_dir()
    files, report = build(check)
    drift = [name for name, data in files.items() if _read(here / name) != data]
    if drift and not check:
        _write_all(here, {name: files[name] for name in files if name in drift})
        _reread_catalog()
    return drift, report


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--check', action='store_true',
                    help='compare with the installed workspace; write nothing')
    args = ap.parse_args(argv)
    try:
        drift, report = refresh_with_report(args.check)
    except Refused as exc:
        print(f'catalog refresh REFUSED, nothing written: {exc}', file=sys.stderr)
        return 2
    for line in report:
        print(line)
    if args.check:
        print('catalog up to date' if not drift else f'catalog DRIFT: {", ".join(drift)} '
              f'(run {REFRESH})')
        return 1 if drift else 0
    print('catalog refreshed: ' + (', '.join(drift) if drift else 'nothing changed'))
    return 0


if __name__ == '__main__':
    sys.exit(main())
