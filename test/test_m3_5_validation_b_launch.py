RUNNER_END = re.compile(r'\[trainit_run_bt-\d+\]: process has (finished cleanly|died \[pid \d+, exit code (-?\d+))')


class _UntilTheRunnerEnds:
    """The runner launch's process, waited on until trainit_run_bt itself has ended: the launch also
    runs the bundle's detector node, which keeps it up after the tree is done (as in every bundle with
    a detector), so the harness then stops it (SIGINT) and the RUNNER's exit is read from the log."""

    def __init__(self, popen: subprocess.Popen, log: Path):
        self.popen, self.log, self.waited = popen, log, False

    def wait(self, timeout=None):
        if self.waited:                               # the stop's own wait: the process's
            return self.popen.wait(timeout=timeout)
        self.waited = True
        end = time.monotonic() + (timeout or 0)
        while time.monotonic() < end:
            if self.popen.poll() is not None:
                return self.popen.returncode
            text = self.log.read_text(errors='replace') if self.log.is_file() else ''
            if RUNNER_END.search(text):
                raise subprocess.TimeoutExpired('trainit_bt.launch.py', 0)   # done: stop the detector too
            time.sleep(0.5)
        raise subprocess.TimeoutExpired('trainit_bt.launch.py', timeout)

    def __getattr__(self, name):
        return getattr(self.popen, name)


class ValidationBLaunch:
    """The sample's harness (bring-up, then the runner) on the M3-C bundle, on its own domain."""

    def __init__(self, ws: Path):
        self.base = _sample_launch().SampleLaunch(ws)
        self.base.env['ROS_DOMAIN_ID'] = str(DOMAIN)
        launch = self.base._launch

        def _launch(what, log):
            popen = launch(what, log)
            return _UntilTheRunnerEnds(popen, log) if 'trainit_bt.launch.py' in what else popen
        self.base._launch = _launch

    def run(self) -> 'ValidationBLaunch':
        S, b = _sample_launch(), self.base
        saved = (S.DOMAIN, S.PREFIX)
        S.DOMAIN, S.PREFIX = DOMAIN, PREFIX
        try:
            b.run()
        finally:
            S.DOMAIN, S.PREFIX = saved
        log = b.logs / 'runner.log'
        self.runner = log.read_text(errors='replace') if log.is_file() else ''
        bringup = b.logs / 'bringup.log'
        self.bringup = bringup.read_text(errors='replace') if bringup.is_file() else ''
        self.events = EVENT.findall(self.runner)
        self.triggers = [int(k) for k in re.findall(r'\[fake\] trigger (\d+): a STALE', self.runner)]
        self.captured = re.findall(r"DetectObject: 'part' score [\d.]+ at \(([-\d.]+), [-\d.]+, [-\d.]+\) in "
                                   r'base_link -> BB\[(captures\.\d)\.\*\]', self.runner)
        self.fresh = re.findall(r'fresh result on \S+ after (\d+) trigger\(s\) \((\d+) stale rejected\)',
                                self.runner)
        self.stale = self.runner.count('DetectObject: stale result rejected')
        self.lamp = re.findall(r'inspection_light/process_enabled = (True|False)', self.runner)
        self.never = sorted(n for n in NEVER if n in self.runner or n in self.bringup)
        end = RUNNER_END.search(self.runner)
        self.runner_exit = None if end is None else (0 if end.group(1).startswith('finished') else int(end.group(2)))
        b.say(f'[runner] trainit_run_bt exit {self.runner_exit} (the launch is then stopped: its detector '
              'node keeps it up)')
        for line in (f'[runner] events {self.events}', f'[fake] triggers {self.triggers}',
                     f'[runner] captures {self.captured}', f'[runner] fresh {self.fresh}; stale rejected '
                     f'{self.stale}', f'[fake] lamp driver received {self.lamp}',
                     f'[logs] lines that must never appear: {self.never or "none"}'):
            b.say(line)
        return self


