def _why(m3c) -> str:
    return '\n' + m3c['run'].base.report()


def test_m3c_the_program_generates_and_builds(m3c):
    assert [w for w in m3c['manifest'].warnings if 'm3c_fake_detector' not in w] == []
    assert '4 packages finished' in m3c['summary'], m3c['summary']
    assert m3c['floors']['trainit_motion_runtime'] == (2, 4, 0)


def test_m3c_the_bring_up_comes_up_on_mock(m3c):
    ready = m3c['run'].base.ready
    assert ready and all(ready.values()), _why(m3c)


def test_m3c_validation_b_ends_bt_finished_success(m3c):
    b = m3c['run'].base
    assert (b.finished, m3c['run'].runner_exit) == ('SUCCESS', 0), _why(m3c)


def test_m3c_the_path_runs_split_at_its_events_in_the_programs_order(m3c):
    assert m3c['run'].events == EXPECTED, _why(m3c)


def test_m3c_three_triggers_in_order_and_three_fresh_captures(m3c):
    run = m3c['run']
    assert run.triggers == [1, 2, 3], _why(m3c)
    assert run.captured == [('0.1000', 'captures.0'), ('0.2000', 'captures.1'), ('0.3000', 'captures.2')], _why(m3c)
    # each capture: one trigger, its stale answer rejected (by its stamp), the fresh one accepted
    assert run.fresh == [('1', '1'), ('1', '1'), ('1', '1')], _why(m3c)
    assert run.stale >= 3, _why(m3c)
    assert '7.7' not in ' '.join(x for x, _k in run.captured) and '9.9' not in ' '.join(x for x, _k in run.captured)


def test_m3c_the_logical_channel_reaches_the_lamp_driver(m3c):
    assert m3c['run'].lamp == ['True', 'False'], _why(m3c)


def test_m3c_no_log_names_a_refusal_a_timeout_or_a_failed_motion(m3c):
    assert m3c['run'].never == [], _why(m3c)


def test_m3c_every_launch_ends_cleanly_and_the_domain_is_empty_before_and_after(m3c):
    b = m3c['run'].base
    assert b.guards == {'before': [], 'after': []}, _why(m3c)
    assert b.stops == {'runner': 'clean', 'bring-up': 'clean'}, _why(m3c)
