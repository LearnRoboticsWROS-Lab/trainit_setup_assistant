def test_a_fault_is_logged_with_its_reason_and_ends_the_run(gate):
    """§7 / §11: a FAULT is never retried, recovered or read as an empty bin: the program logs it and its reason
    and ends -- one detection (3, 3b, 6b, 11), the second engage (10) or the start check (12) and nothing after."""
    detections = {'c10_terminal_fault': 2, 'c12_unknown_at_start': 0}
    for case_id in ('c03_unavailable', 'c03b_provider_absent', 'c06b_stale_always', 'c10_terminal_fault',
                    'c11_place_unreachable', 'c12_unknown_at_start'):
        run = gate['gate'].result(case_id)
        reason = next(e.split(':', 1)[1] for e in BY_ID[case_id].events if e.startswith('FAULT:'))
        assert 'FAULT: the run stops (application.faults: stop), never retried or recovered; the reason follows' \
            in run.bt_lines, run.why()
        assert reason in run.bt_lines, run.why()
        assert run.counts['detect'] == detections.get(case_id, 1), run.why()
        assert not {'bin_empty', 'pickable_exhausted', 'recovery_exhausted'} & set(run.events), run.why()
    # a capture is bounded by its timeout_ms (3000) and re-triggers every 500 ms: 5..7 triggers, then the fault
    for case_id, stale in (('c03_unavailable', False), ('c06b_stale_always', True)):
        run = gate['gate'].result(case_id)
        assert len(run.triggers) == 1 and 5 <= run.triggers[0][0] <= 7, run.why()
        assert run.triggers[0][1] == (run.triggers[0][0] if stale else 0), run.why()
    # the producer's own refusal is carried in the DETECTION_TIMEOUT's cause
    assert 'the producer last answered: scripted: perception unavailable' in gate['gate'].result('c03_unavailable').text
    assert "service '/perception/capsules/detect' did not answer" in gate['gate'].result('c03b_provider_absent').text


