def _short(wp: str) -> str:
    for prefix, short in SHORT:
        if wp.startswith(prefix):
            return short + wp[len(prefix):]
    return wp


def read_events(text: str) -> list:
    """The runner's events in order; ``FAULT:<reason>`` takes the reason from the program's next [BT] line."""
    out = []
    bt_lines = BT_LOG.findall(text)
    for m in EVENT.finditer(text):
        g = m.groupdict()
        if g['n'] is not None:
            out.append(f'detect:{g["n"]}')
        elif g['dfail']:
            out.append(f'detect:{g["dfail"]}')
        elif g['cid']:
            out.append(f'try:{g["cid"]}')
        elif g['wp']:
            out.append(f'move:{_short(g["wp"])}')
        elif g['plan']:
            out.append('planfail')
        elif g['grip']:
            what = 'engage' if g['grip'] == 'CloseGripper' else 'open'
            out.append(what if g['gres'] == 'SUCCESS' else f'{what}:{g["gres"]}')
        elif g['vexp']:
            out.append(f'{g["vexp"]}:{g["vres"]}')
        elif g['attach']:
            out.append('attach')
        elif g['detach']:
            out.append('detach')
        elif g['fault']:
            i = next((k for k, line in enumerate(bt_lines) if line.startswith('FAULT: the run stops')), None)
            reason = bt_lines[i + 1].strip() if i is not None and i + 1 < len(bt_lines) else '?'
            out.append(f'FAULT:{reason}')
        elif g['pempty']:   # TSA 8.7.0: the presence capture
            out.append('presence:EMPTY')
        elif g['ppresent']:
            out.append('presence:PRESENT')
        elif g['outcome']:
            out.append(f'OUTCOME:{g["outcome"]}')
        elif g['end']:      # TSA 8.6.2 logs "nothing pickable"; the event keeps its name
            out.append('nothing_to_pick' if g['end'] == 'nothing pickable' else g['end'].replace(' ', '_'))
        elif g['bt']:
            out.append(f'BT:{g["bt"]}')
    return out


class _UntilTheRunnerEnds:
    """The runner launch, waited on until trainit_run_bt itself has exited; ``ended`` tells a finished runner from
    the wall bound. TSA 8.6.1: the launch then ENDS BY ITSELF (the runner's exit shuts down the provider node that
    kept it up before: test_launch_ends_with_tree.py) -- ``self_ended`` records that it did, within
    SELF_END_S of the runner's exit, without the harness stopping it."""

    SELF_END_S = 20.0

    def __init__(self, popen: subprocess.Popen, log: Path):
        self.popen, self.log, self.waited, self.ended, self.self_ended = popen, log, False, False, False

    def wait(self, timeout=None):
        if self.waited:
            return self.popen.wait(timeout=timeout)
        self.waited = True
        end = time.monotonic() + (timeout or 0)
        while time.monotonic() < end:
            if self.popen.poll() is not None:
                self.ended = self.self_ended = True
                return self.popen.returncode
            text = self.log.read_text(errors='replace') if self.log.is_file() else ''
            if RUNNER_END.search(text):
                self.ended = True
                try:                             # the launch's own shutdown (end_with_tree), given its time
                    code = self.popen.wait(timeout=self.SELF_END_S)
                    self.self_ended = True
                    return code
                except subprocess.TimeoutExpired:
                    raise subprocess.TimeoutExpired('trainit_bt.launch.py', 0)    # it did not: stop it
            time.sleep(0.5)
        raise subprocess.TimeoutExpired('trainit_bt.launch.py', timeout)

    def __getattr__(self, name):
        return getattr(self.popen, name)


