"""Generate ``_app/config/perception.yaml`` from the project PerceptionSpec.

One entry per detector; the ``_app`` launch runs one ``trainit_perception``
``detector_node`` per PURE-PYTHON entry (external-node methods publish the same
contract from their own node). ``params`` is the tuned dict VERBATIM — the live
tuner and this file serialize the same thing, which is the "TSA generates what you
tuned" guarantee.

On top of the tuned dict this module writes the CANDIDATE RANKING (ADR-0017): the rule
itself, plus the three numbers its terms are computed from. They are parameters of the
DETECTOR because that is where ADR-0017 Decision 1 put the rank — the publisher's
ordering step is the one place the order is decided — but two of them are properties of
the TOOL and one is a property of the OBJECT, so the generator is where the three parts
of the model are joined. Each lands only when it has a value, exactly the way ``blur_px``
and the depth bounds do: ``perception.yaml`` is compared YAML-semantically against the
golden, so a key that always appeared would silently re-bless every published bundle.

Loaded with ``yaml.safe_load`` by ``detector_node`` (a plain config file, not ROS 2
parameters), so typing is python-level; floats are still emitted as floats for
readability and to match the runtime profile documentation.
"""

from __future__ import annotations

from typing import Any, Dict, List, Tuple

import yaml

from ..model import CanonicalProject
from ..model.faces import (DEFAULT_FACE, all_face_params, face_problem,
                           face_params as registered_face_params)
from ..model.perception import (DetectorSpec, candidate_rule_refusal,
                                effective_candidate_rule, missing_candidate_terms)

_HEADER = (
    '# Generated by the TrainIt Setup Assistant from the project PerceptionSpec\n'
    '# (the Perception step). One entry per detector; the _app launch runs one\n'
    '# trainit_perception detector_node per pure-python entry. The tree\'s\n'
    '# DetectObject consumes /perception/<name>/detections.\n'
)

# The ranking parameters that do NOT depend on which grasp face is configured. The app
# emitter pins the trainit_perception version that understands them off this same list — a
# new ranking parameter must not be able to reach a bundle without moving the floor that
# guarantees the runtime reads it — so the list has to be complete, which is why the face's
# own parameters are ASKED of the registry in :func:`ranking_param_names` instead of being
# spelled out here (ADR-0018 Decision 6).
FIXED_RANKING_PARAMS = ('candidate_rule', 'grasp_face', 'tool_radius_m', 'tool_reach_mm')


def ranking_param_names() -> Tuple[str, ...]:
    """Every parameter the ranking can write, every face in TSA's snapshot of the registry
    included.

    A FUNCTION and not a constant, because the answer depends on the face registry: the
    moment ``trainit_perception`` registers another face family and the catalog is refreshed,
    its parameters are ranking parameters here too — pinned by the same mechanism, offered by
    the same GUI — without a line of this module changing. That is the whole of Decision 6: a hand-written ``rect`` face used
    to be ACCEPTED by the runtime and REFUSED by TSA, because this list was a fixed
    four-tuple that never even wrote ``grasp_face``.
    """
    return FIXED_RANKING_PARAMS + all_face_params()


def face_params_for(project: CanonicalProject, tuned: Dict[str, Any]) -> Dict[str, Any]:
    """The GRASP FACE this detector ranks against: the face token and its own numbers.

    Three ways a face is configured, in the order they win:

    1. a value already in the tuned ``params`` — a hand-edited profile is data the GUI
       cannot see, and an upsert must not strip it;
    2. the MEASURED face on the grasp target (ADR-0018): the face family and the numbers
       the picker measured off the object's own CAD, keyed by the parameters the registry
       says that face reads;
    3. the bounding-box disc radius, which is what TSA did before the picker existed —
       28,10 mm against a true 20,95 mm on the reference capsule, so it is the fallback and
       no longer the answer.

    ``grasp_face`` lands only when the face is NOT the registry's default, the way
    ``blur_px`` and the depth bounds land only when they are on: ``perception.yaml`` is
    compared YAML-semantically against the golden, so a key that always appeared would
    silently re-bless every published bundle.
    """
    out: Dict[str, Any] = {}
    name, measured = project.scene.grasp_face()
    face = name or DEFAULT_FACE
    if name and name != DEFAULT_FACE and 'grasp_face' not in tuned:
        out['grasp_face'] = name
    # What this face is configured BY comes from the registry (TSA's snapshot of it); what TSA
    # has to fill comes from the measurement. For a face the snapshot does not register, the
    # measured keys are written as they are — and the face itself is refused, once, by name
    # (`candidate_rule_problems`), as the node would refuse it at start-up.
    wanted = registered_face_params(face) or tuple(measured)
    for key in wanted:
        if key in tuned:
            continue
        value = measured.get(key)
        if value is None and face == DEFAULT_FACE and key == 'expected_radius_m':
            # The ONE parameter TSA can supply without a measurement, and the one name in
            # this file: the bounding-box disc radius. It is gated on the DEFAULT face
            # because that is the face it was written for — applying an x·y disc to, say, a
            # cylinder's side would be TSA inventing a meaning for a parameter it does not
            # own, which is the hardcoding Decision 6 removes.
            value = project.scene.grasp_face_radius_m() or None
        if value is not None and float(value) > 0:
            out[key] = round(float(value), 5)
    return out


def ranking_params(project: CanonicalProject, det: DetectorSpec) -> Dict[str, Any]:
    """The candidate-ranking parameters this detector gets on top of its tuned dict.

    Three sources, one dict (ADR-0017):

    - ``candidate_rule`` — the detector's own field, written only when SET.
    - the GRASP FACE — ``grasp_face`` plus the parameters THAT face reads, from the grasp
      target: measured off its CAD when the picker measured it (ADR-0018), derived from its
      shape and dims otherwise. Gated on a rule being set, because a derived number must
      not appear in a bundle whose ranking was never configured. Which parameters those
      are is the REGISTRY's answer, not a list in this file (ADR-0018 Decision 6).
    - ``tool_radius_m`` / ``tool_reach_mm`` — the TOOL's geometry, from ``GripperSpec``
      (the footprint radius and the GRIP WINDOW). NOT gated on the rule: ``clearance``
      ships as a published term without being a ranking default (ADR-0017 Decision 4), so
      a cell that declares its tool gets the term whatever it ranks by.

    A value already present in the tuned ``params`` always wins: a hand-edited profile is
    data the GUI cannot see, and an upsert must not strip it.
    """
    out: Dict[str, Any] = {}
    grip = project.robot.gripper
    rule = effective_candidate_rule(det)
    if rule is not None:
        out['candidate_rule'] = rule.value
        # The face is what `visible_fraction` divides by, and nothing is written when the
        # grasp target supplies no size: 0 means "no face area", and the refusal below
        # turns that into a message instead of a silent demotion to `candidate_2d3d`.
        out.update(face_params_for(project, det.params))
    if grip.tool_radius_m > 0 and 'tool_radius_m' not in det.params:
        out['tool_radius_m'] = float(grip.tool_radius_m)
    if grip.tool_reach_mm > 0 and 'tool_reach_mm' not in det.params:
        out['tool_reach_mm'] = float(grip.tool_reach_mm)
    return out


def detector_params(project: CanonicalProject, det: DetectorSpec) -> Dict[str, Any]:
    """The full params dict for one detector: the tuned dict + the ranking parameters."""
    params = dict(det.params)
    params.update(ranking_params(project, det))
    return params


def candidate_rule_problems(project: CanonicalProject) -> List[str]:
    """Every configured rule whose terms are not computable, as refusal messages.

    Plus a ``grasp_face`` the registry does not know, which fails the same way and so is
    refused in the same place: the detector node builds its face where it reads the file,
    so an unknown name stops the node at start-up and the cell publishes nothing. The
    registry is TSA's committed snapshot of trainit_perception's (ADR-0021, amendment M2.2),
    so the answer is the same on every machine, perception package installed or not.

    Pure, so the GUI can show the same text the generator would raise.
    """
    per = project.perception
    problems: List[str] = []
    for det in (per.detectors if per else []):
        rule = effective_candidate_rule(det)      # raises on an unknown hand-edited token
        params = detector_params(project, det)
        bad_face = face_problem(params)
        if bad_face:
            problems.append(f'detector "{det.name}": {bad_face}')
        if rule is None:
            continue
        missing = missing_candidate_terms(rule, det.method, params)
        if missing:
            problems.append(
                candidate_rule_refusal(det.name, rule, det.method, missing, params))
    return problems


def refuse_uncomputable_candidate_rules(project: CanonicalProject) -> None:
    """REFUSE a rule whose terms are not computable (ADR-0017 Decision 3).

    A hard ``ValueError``, not a manifest warning: every other generation problem leaves
    a partial bundle that still helps, but a bundle whose ranking cannot be computed is
    worse than no bundle — it runs, it picks in the model's own order, and it looks like a
    perception fault. Called from the orchestrator BEFORE the first file is written, and
    again from :func:`build_perception_yaml`, so the file cannot be produced by any other
    caller either. The name is checked where it is read, mirroring the runtime's own check
    on the same file.
    """
    problems = candidate_rule_problems(project)
    if problems:
        raise ValueError('\n'.join(problems))


def build_perception_yaml(project: CanonicalProject) -> str:
    refuse_uncomputable_candidate_rules(project)
    per = project.perception
    cam = per.camera if per else None
    detectors = {}
    for d in (per.detectors if per else []):
        detectors[d.name] = {
            'method': d.method.value,
            # ONE resolution of the camera contract, on the model
            # (``DetectorSpec.input_topics``): this file and the launch entry of an
            # external-node detector must never name different topics.
            'input': d.input_topics(cam),
            'params': detector_params(project, d),
            'continuous': bool(d.continuous),
            'rate_hz': float(d.rate_hz),
        }
    body = yaml.safe_dump({'detectors': detectors}, sort_keys=False,
                          default_flow_style=None)
    return _HEADER + body
