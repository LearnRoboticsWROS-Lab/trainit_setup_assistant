O1_WORDS = {'N1': {'BUSY', 'DONE'}, 'F1': {'FAULT'}, 'F2': {'TIMEOUT'}, 'F7': {'UNAVAILABLE'}}


def test_o1_the_machine_states_in_plain_words_on_every_surface_never_a_topic_or_a_counter(machine):
    run = machine['run']
    texts = {'rti': [], 'plc': [], 'panel': []}
    for case in ('N1', 'F1', 'F2', 'F7'):
        r = _rec(machine, case)
        texts['rti'] += r['running'] + [r['detail']]
        texts['plc'] += [t for t in r['plc'] if 'MACHINE' in t]
    for key in ('ready', 'done_idle'):
        r = _rec(machine, 'N3')[key]
        texts['rti'] += r['running'] + [r['detail']]
        texts['plc'] += [t for t in r['plc'] if 'MACHINE' in t]
    per_case = [(case, _rec(machine, case), want) for case, want in O1_WORDS.items()] + \
        [(f'N3 {key}', _rec(machine, 'N3')[key], {'DONE'}) for key in ('ready', 'done_idle')]
    for case, r, want in per_case:
        for surface, items in (('rti', r['running'] + [r['detail']]), ('plc', r['plc'])):
            shown = {w for t in items for w in H.machine_words(t)}
            assert want <= shown, (case, surface, sorted(want - shown), items)
    jobs = {_rec(machine, c)['job'] for c in ('N1', 'F1', 'F2', 'F7')} | \
        {_rec(machine, 'N3')[k]['job'] for k in ('ready', 'done_idle')}
    for log in run.server_logs:
        lines = log.read_text(errors='replace').splitlines() if log.exists() else []
        for j in sorted(jobs):
            texts['panel'] += H.run_panel_states(_job_window(lines, j))
    for surface, items in texts.items():
        words = {w for t in items for w in H.machine_words(t)}
        want = {'WAITING', 'BUSY', 'DONE', 'FAULT', 'TIMEOUT', 'UNAVAILABLE'}
        assert want <= words, (surface, sorted(want - words), items[:40])
        leaks = [t for t in items if H.PROTOCOL.search(t)]
        assert leaks == [], (surface, leaks)


def _job_window(lines: list, j: int) -> list:
    """The server log lines of job j: from its first `RTI: job j` line to its end line and the state line after it."""
    start = next((i for i, ln in enumerate(lines) if re.search(rf'RTI: job {j}\b', ln)), None)
    if start is None:
        return []
    end = next((i for i in range(start, len(lines)) if re.search(rf'RTI: job {j} \(.*\) ended', lines[i])), None)
    return lines[start:(len(lines) if end is None else min(len(lines), end + 3))]


