"""M3-A, LAUNCHED (opt-in): Validation A -- the Canonical Task Program of the public UR5e sample cell,
``examples/ur5e_suction/task_program.yaml`` -- generated by the TSA under test into a temp
workspace, built, brought up on mock and run (vNext M3.3, ADR-0024).

    generate the program the README's way (from its directory), renamed to tprog_* so it never
      collides with a bundle the user built
      -> colcon build over the sourced workspace: 3 packages
      -> ``ros2 launch tprog_app bringup.launch.py mode:=mock rviz:=false``: move_group ready, the
         arm controller active, the trainit_mock adapter for /eef/main up
      -> ``ros2 launch tprog_app trainit_bt.launch.py use_sim_time:=false groot_monitor:=false``:
         the runner loads config/paths.yaml (1 path), the tree adds the table, runs task_validation_a
         -- HOME, PTP W1, LIN W2, CIRC W3 (via W2b), LIN W4, PTP HOME as single moves, then PTP W1
         and the same motion as ONE blended path (FollowPath 'sweep', provider pilz_sequence),
         then HOME -- and ends ``BT finished: SUCCESS`` with exit 0; every pose was taught in UR's
         `base` frame and resolved through TF; no log names a refused path, profile or frame, a
         failed plan or validation, or a contact
      -> both launches end within 30 s of their SIGINT and leave no process; ROS domain 78 holds no
         node before and none after

OPT-IN: ``TRAINIT_LAUNCH_TEST=1`` and a sourced workspace (ROS 2 Humble + the TrainIt workspace
with trainit_motion_runtime 2.2.0). It skips, naming the cause, with an older trainit_motion_runtime
or trainit_hardware_layer than the generated package.xml declares, without ur_description and
xacro, or when the machine lacks what the bundle declares (``launch_prereqs``). Every launch runs
in its own session on ROS domain 78 (no other TrainIt test uses it), ROS_LOCALHOST_ONLY=1, with
TMPDIR and ROS_LOG_DIR inside the temp workspace. Test-time generation, removed at teardown. With
``TRAINIT_M3A_EVIDENCE=<dir>`` the report and every launch log are copied to ``<dir>/m3_a/``.
"""
import os
import re
import shutil
import xml.etree.ElementTree as ET
from pathlib import Path

import pytest

pytestmark = pytest.mark.skipif(os.environ.get('TRAINIT_LAUNCH_TEST') != '1',
                                reason='opt-in: set TRAINIT_LAUNCH_TEST=1 (builds and launches)')

EXAMPLE = Path(__file__).resolve().parents[1] / 'examples' / 'ur5e_suction'
PREFIX = 'tprog'
DOMAIN = 78
EVIDENCE = 'TRAINIT_M3A_EVIDENCE'
MOVES = ['home', 'w1', 'w2', 'w3', 'w4', 'home', 'w1', 'home']
EXPECTED = ["added collision box 'table'",
            *[f"MoveWaypoint '{w}'" for w in MOVES[:7]],
            "FollowPath 'sweep' (4 states, provider=pilz_sequence, continuity=blend): OK",
            f"MoveWaypoint '{MOVES[7]}'",
            'BT finished: SUCCESS']
EVENT = re.compile(r"\]: (added collision box '\w+'|MoveWaypoint '\w+'(?= \()"
                   r"|FollowPath '\w+' \([^)]*\): \S+|BT finished: \w+)")
NEVER = ('REFUSED', 'NOT_AT_PATH_START', 'FRAME_UNRESOLVED', 'is not a loaded motion profile',
         'PLAN FAILED', 'VALIDATION FAILED', 'Found a contact between',
         'No geometry is associated to any robot links', 'does not include the parent link')


def _sample_launch():
    import test_example_ur5e_suction_launch as S
    return S


class ProgramLaunch:
    """The bring-up, then the runner, on the task-program bundle built in ws (the sample's harness,
    on its own domain and package names)."""

    def __init__(self, ws: Path):
        self.base = _sample_launch().SampleLaunch(ws)
        self.base.env['ROS_DOMAIN_ID'] = str(DOMAIN)

    def run(self) -> 'ProgramLaunch':
        S, b = _sample_launch(), self.base
        saved = (S.DOMAIN, S.PREFIX)
        S.DOMAIN, S.PREFIX = DOMAIN, PREFIX     # the harness's guards and launches, ours
        try:
            b.run()
        finally:
            S.DOMAIN, S.PREFIX = saved
        runner_log = b.logs / 'runner.log'
        self.runner = runner_log.read_text(errors='replace') if runner_log.is_file() else ''
        bringup_log = b.logs / 'bringup.log'
        self.bringup = bringup_log.read_text(errors='replace') if bringup_log.is_file() else ''
        self.events = EVENT.findall(self.runner)
        self.moves = re.findall(r"\]: MoveWaypoint '(\w+)' \(", self.runner)
        self.paths_loaded = re.findall(r'paths_file \S+: (\d+) path\(s\)', self.runner)
        self.never = sorted(n for n in NEVER if n in self.runner or n in self.bringup)
        for line in (f'[runner] events {self.events}', f'[runner] paths loaded {self.paths_loaded}',
                     f'[logs] lines that must never appear: {self.never or "none"}'):
            b.say(line)
        return self

    def report(self) -> str:
        return self.base.report()


@pytest.fixture(scope='module')
def m3a(tmp_path_factory):
    import composite_launch as CL
    if not os.environ.get('COLCON_PREFIX_PATH'):
        pytest.skip('needs a sourced workspace (ROS 2 Humble + the TrainIt workspace install)')
    import test_example_ur5e_suction as S
    S.needs_ur_description()
    from trainit_setup_assistant.generator import Orchestrator
    from trainit_setup_assistant.model import BundleSpec, load_project
    tmp = tmp_path_factory.mktemp('m3a_ws')
    try:
        ws = CL._outside_the_underlay(tmp)
        with pytest.MonkeyPatch.context() as mp:
            mp.chdir(EXAMPLE)
            project = load_project('task_program.yaml')
            project.bundle = BundleSpec.from_prefix(PREFIX)
            manifest = Orchestrator().generate(project, ws / 'src' / PREFIX)
        app_xml = ws / 'src' / PREFIX / f'{PREFIX}_app' / 'package.xml'
        floors = {e.text.strip(): tuple(int(x) for x in e.get('version_gte').split('.'))
                  for e in ET.parse(app_xml).getroot().iter('exec_depend')
                  if e.get('version_gte')}
        for package, floor in sorted(floors.items()):
            have = CL.installed_version(package)
            if have < floor:
                pytest.skip(f'{package} {CL._v(have)} is installed; the bundle declares '
                            f'>= {CL._v(floor)}')
        import launch_prereqs
        launch_prereqs.require(ws / 'src', modules=CL.PROBE_MODULES)
        summary = CL.build(ws)
        run = ProgramLaunch(ws)
        try:
            run.run()
        finally:
            if os.environ.get(EVIDENCE):
                run.base.save(Path(os.environ[EVIDENCE]) / 'm3_a')
        yield dict(manifest=manifest, summary=summary, run=run, floors=floors)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def _why(m3a) -> str:
    return '\n' + m3a['run'].report()


def test_m3a_the_program_generates_and_builds(m3a):
    assert m3a['manifest'].warnings == []
    assert '3 packages finished' in m3a['summary'], m3a['summary']
    assert m3a['floors']['trainit_motion_runtime'] == (2, 2, 0)


def test_m3a_the_bring_up_comes_up_on_mock(m3a):
    ready = m3a['run'].base.ready
    assert ready and all(ready.values()), _why(m3a)


def test_m3a_the_runner_loads_the_path_library(m3a):
    assert m3a['run'].paths_loaded == ['1'], _why(m3a)


def test_m3a_validation_a_ends_bt_finished_success(m3a):
    b = m3a['run'].base
    assert (b.timed_out, b.finished, b.code) == (False, 'SUCCESS', 0), _why(m3a)


def test_m3a_every_step_runs_in_the_programs_order(m3a):
    run = m3a['run']
    assert run.moves == MOVES, _why(m3a)
    assert run.events == EXPECTED, _why(m3a)


def test_m3a_no_log_names_a_refusal_a_failed_motion_or_a_contact(m3a):
    assert m3a['run'].never == [], _why(m3a)


def test_m3a_every_launch_ends_cleanly_and_the_domain_is_empty_before_and_after(m3a):
    b = m3a['run'].base
    assert b.guards == {'before': [], 'after': []}, _why(m3a)
    assert b.stops == {'runner': 'clean', 'bring-up': 'clean'}, _why(m3a)
