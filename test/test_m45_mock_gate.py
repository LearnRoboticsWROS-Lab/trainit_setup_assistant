class CaseRun:
    """One case: the sample's harness (guard, bring-up, runner, clean stops, guard) on this gate's domain, with
    this case's bundle, log directory and wall bound."""

    def __init__(self, ws: Path, case: Case):
        self.case = case
        self.base = _sample_launch().SampleLaunch(ws)
        self.base.env['ROS_DOMAIN_ID'] = str(DOMAIN)
        self.base.logs = ws / 'logs' / case.id
        self.base.logs.mkdir(parents=True, exist_ok=True)
        self.runner = None
        launch = self.base._launch

        def _launch(what, log):
            popen = launch(what, log)
            if 'trainit_bt.launch.py' in what:
                self.runner = _UntilTheRunnerEnds(popen, log)
                return self.runner
            return popen
        self.base._launch = _launch

    def run(self) -> 'CaseRun':
        S, b = _sample_launch(), self.base
        saved = (S.DOMAIN, S.PREFIX, S.TREE_TIMEOUT_S)
        S.DOMAIN, S.PREFIX, S.TREE_TIMEOUT_S = DOMAIN, self.case.bundle, self.case.wall_s
        t0 = time.monotonic()
        try:
            b.run()
        finally:
            S.DOMAIN, S.PREFIX, S.TREE_TIMEOUT_S = saved
        self.wall = time.monotonic() - t0
        log = b.logs / 'runner.log'
        text = log.read_text(errors='replace') if log.is_file() else ''
        self.text = text
        self.ended = bool(self.runner and self.runner.ended)
        self.self_ended = bool(self.runner and self.runner.self_ended)
        end = RUNNER_END.search(text)
        self.exit = None if end is None else (0 if end.group(1).startswith('finished') else int(end.group(2)))
        self.events = read_events(text)
        self.triggers = [(int(a), int(s)) for a, s in TRIGGERS.findall(text)]
        self.counts = {k: sum(e == k or e.startswith(k + ':') for e in self.events)
                       for k in ('detect', 'try', 'engage', 'planfail', 'move')}
        self.counts['triggers'] = sum(a for a, _ in self.triggers)
        self.bt_lines = BT_LOG.findall(text)
        b.say(f'[{self.case.id}] runner ended {self.ended}; launch ended by itself {self.self_ended}; '
              f'BT finished {b.finished}; exit {self.exit}; '
              f'wall {self.wall:.1f} s')
        b.say(f'[{self.case.id}] events {self.events}')
        b.say(f'[{self.case.id}] counts {self.counts}; triggers per capture {self.triggers}')
        b.say(f'[{self.case.id}] [BT] lines {self.bt_lines}')
        return self

    def why(self) -> str:
        return '\n' + self.base.report()


class Gate:
    def __init__(self, ws: Path, scenario_paths: dict):
        self.ws, self.scenario_paths, self.runs = ws, scenario_paths, {}

    def result(self, case_id: str) -> CaseRun:
        if case_id not in self.runs:
            case = BY_ID[case_id]
            target = self.scenario_paths[case.bundle]
            target.unlink(missing_ok=True)
            if case.scenario:
                shutil.copyfile(SCENARIOS / case.scenario, target)
