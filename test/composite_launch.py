    def _tree(self, n: str, robot: str, tag: str, bt_log: Path, proc=None) -> dict:
        bt = proc or self._launch(f'{robot}_app trainit_bt.launch.py use_sim_time:=false '
                                  f'groot_monitor:=false', bt_log)
        timed_out = False
        try:
            bt.wait(timeout=TREE_TIMEOUT_S)
        except subprocess.TimeoutExpired:
            timed_out = True
        finally:
            outcome = self._stop_outcome(bt)
        self._check_stop(f'shutdown {n} BT {tag}', outcome)
        return self._parse(bt_log.read_text(errors='replace'), timed_out)

    @staticmethod
    def _parse(text: str, timed_out: bool) -> dict:
        died = re.search(r'process has died \[pid \d+, exit code (-?\d+)', text)
        clean = 'process has finished cleanly' in text
        code = int(died.group(1)) if died else (0 if clean else None)
        finished = re.findall(r'BT finished: (\w+)', text)
        return dict(code=code, timed_out=timed_out,
                    verdicts=VERDICT.findall(text),
                    latch=re.findall(r'end-effector FAULT latched: (\S+ \S+)', text),
                    finished=finished[-1] if finished else None,
                    steps=[(m.group(2), m.group(3), m.group(4), m.group(5))
                           for m in EEF_LINE.finditer(text)],
                    identities=sorted(set(IDENTITY.findall(text))))

