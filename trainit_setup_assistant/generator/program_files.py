_QUOTED = ('named', 'frame', 'tcp', 'profile')


def _num(value) -> str:
    """fmtnum, never in exponent notation (a YAML 1.1 reader takes '1e-07' for a string)."""
    text = fmtnum(value)
    if 'e' in text or 'E' in text:
        text = f'{float(value):.15f}'.rstrip('0')
        text = text + '0' if text.endswith('.') else text
    return text


def _list(values) -> str:
    return '[' + ', '.join(_num(v) for v in values) + ']'


def _scalar(key: str, value) -> str:
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, (int, float)):
        return _num(value)
    if isinstance(value, (list, tuple)):
        return _list(value)
    return f'"{value}"' if key in _QUOTED else str(value)


def task_parameters_lines(plan: ProgramPlan, scene_params, indent: str = '      ') -> List[str]:
    """The ``task_parameters`` block of bt_params.yaml, one line per item (without the key line)."""
    out = [f'{indent}{key}: {fmtlist(vals)}' for key, vals in scene_params]
    for name, keys in plan.entries.items():
        out.append('')
        out += [f'{indent}# {line}' for line in plan.entry_notes.get(name, [])]
        out.append(f'{indent}{name}:')
        out += [f'{indent}  {k}: {_scalar(k, v)}' for k, v in keys.items()]
    return out


def _flow(value) -> str:
    """A small mapping or list inline, YAML flow style (keys are identifiers, values numbers or
    names)."""
    if isinstance(value, dict):
        return '{' + ', '.join(f'{k}: {_flow(v)}' for k, v in value.items()) + '}'
    if isinstance(value, (list, tuple)):
        if all(isinstance(v, (int, float)) and not isinstance(v, bool) for v in value):
            return _list(value)
        return '[' + ', '.join(_flow(v) for v in value) + ']'
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, (int, float)):
        return _num(value)
    return str(value)


PATHS_HEADER = """\
# The application's PATHS (paths.yaml schema 1), generated by the TrainIt Setup Assistant from the
# project's Canonical Task Program. trainit_run_bt loads this file (paths_file) and refuses it at
# start-up if anything is wrong; the BehaviorTree runs a path with ONE <FollowPath path="..."/>,
# as ONE motion, whatever its number of states. A state names a waypoint of config/bt_params.yaml
# (task_parameters.<waypoint>: position, orientation, frame); a path starts where the robot is, at
# its first state. Scalings are the provider's (0..1], resolved by TSA from the profiles.
"""


def paths_yaml(plan: ProgramPlan) -> str:
    lines = [PATHS_HEADER.rstrip('\n'), 'schema_version: 1', 'paths:']
    for pp in plan.paths:
        res = pp.resolution
        shape = ('a dense path' if pp.dense else
                 f'{len(pp.states)} states, continuity {pp.data["continuity"]}')
        lines.append(f'  # {pp.name}: {shape}; {provider_text(res)}')
        lines += [f'  #   {line}' for line in scaling_text(res)]
        lines.append(f'  {pp.name}:')
        for key, value in pp.data.items():
            if key == 'events':
                # vNext M3.5: WHERE the path stops for each event; the action is the BT node
                lines.append('    # the robot stops at each event state; the event itself is the BehaviorTree')
                lines.append('    # node between two runs of this path (FollowPath from= to=), as the program says:')
                lines += [f'    #   {ev.event.describe().replace("`", "")}, {ev.authored}' for ev in pp.events]
                lines.append('    events:')
                lines += [f'      - {_flow(item)}' for item in value]
            elif key in ('states', 'segments'):
                lines.append(f'    {key}:')
                lines += [f'      - {_flow(item)}' for item in value]
            elif key == 'source':
                lines.append('    source:')
                lines.append(f'      generator: {_flow(value["generator"])}')
                lines.append(f'      orientation: {_flow(value["orientation"])}')
            elif key == 'profile':
                lines.append(f'    profile: "{value}"')
            elif isinstance(value, dict):
                lines.append(f'    {key}: {_flow(value)}')
            else:
                lines.append(f'    {key}: {_scalar(key, value)}')
    return '\n'.join(lines) + '\n'


PROFILES_HEADER = """\
# The application's MOTION PROFILES as trainit_run_bt loads them (motion_profiles_file), generated
# by the TrainIt Setup Assistant from the project's motion_profiles. Speeds and accelerations are
# NOT here: TSA resolves them for every move (bt_params.yaml task_parameters.<waypoint>.speed and
# .accel, in percent) and every path (paths.yaml velocity_scaling, acceleration_scaling), because a
# TCP limit gives each motion its own scaling. A profile here carries what TMR takes only from a
# named profile -- the planning budget and the goal tolerance -- and an empty one runs with TMR's
# defaults. A step that names no profile runs with "default", TMR's own base profile.
"""


def motion_profiles_yaml(plan: ProgramPlan) -> str:
    lines = [PROFILES_HEADER.rstrip('\n')]
    if not plan.profiles:
        lines.append('motion_profiles: {}')
    else:
        lines.append('motion_profiles:')
        lines += [f'  {name}: {_flow(entry)}' for name, entry in plan.profiles.items()]
    return '\n'.join(lines) + '\n'


# --- README ---------------------------------------------------------------------------------------

def _pct(value) -> str:
    return f'{fmtnum(value)} %'


def _target_text(t) -> str:
    if t.type == 'joint':
        return f'joint, named state `{t.named}`' if t.named else f'joints {fmtlist(t.joints)} rad'
    text = f'pose {fmtlist(t.position)} m, {fmtlist(t.orientation)}'
    if t.derivation:
        text += f' (= {t.derivation})'
    return text


