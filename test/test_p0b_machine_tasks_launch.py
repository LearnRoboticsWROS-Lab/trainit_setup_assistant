def _cells(ws: Path) -> dict:
    """The PUBLIC neutral-station file as trainit_cell_io installs it, and the test's variants of it (device speeds
    and a service id only)."""
    from ament_index_python.packages import get_package_share_directory
    share = Path(get_package_share_directory('trainit_cell_io')) / 'examples' / 'neutral_station'
    out = ws / 'cells'
    out.mkdir(parents=True, exist_ok=True)
    public = out / 'cell_io_mock.yaml'
    shutil.copy(share / 'cell_io_mock.yaml', public)
    base = yaml.safe_load(public.read_text())
    assert base['plant'] == 'mock' and set(base['services']) == {'turner', 'indexer'}, base

    def variant(name, change):
        data = yaml.safe_load(public.read_text())
        change(data)
        path = out / f'cell_io_{name}.yaml'
        path.write_text(yaml.safe_dump(data, sort_keys=False))
        return path

    def typo(d):                                    # PB-P8: the cell's file names the line indexer `indexr`
        d['services'] = {('indexr' if k == 'indexer' else k): v for k, v in d['services'].items()}

    def fast(d, jitter=0.0, seed=1):                # N4 / R1: the same logic and timeouts, quicker devices
        d['mock']['seed'], d['mock']['jitter'] = seed, jitter
        d['mock']['devices']['clamp'] = {'close_ms': 20, 'open_ms': 20}
        d['mock']['devices']['table'] = dict(d['mock']['devices']['table'], speed=3600.0)
        d['mock']['devices']['index'] = dict(d['mock']['devices']['index'], speed=6000.0)
    return dict(public=public, typo=variant('typo', typo), fast=variant('fast', fast),
                r1=variant('r1', lambda d: fast(d, jitter=0.5, seed=7)),
                isaac=share / 'cell_io_isaac.yaml')


