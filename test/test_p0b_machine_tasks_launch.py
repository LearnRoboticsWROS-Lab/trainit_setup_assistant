def _why(machine, *cases) -> str:
    run = machine['run']
    recs = {c: run.records.get(c) for c in cases}
    return '\n' + json.dumps(dict(records=recs, errors=run.errors), indent=1, default=str)[:20000]


def _rec(machine, case: str) -> dict:
    run = machine['run']
    if case not in run.records:
        pytest.fail(f'{case}: no record (its scene failed){_why(machine, case)}')
    return run.records[case]


def _ok(r) -> bool:
    return (r['result'], r['code']) == (H.SUCCEEDED, H.OK)


def _failed(r, code) -> bool:
    return (r['result'], r['code']) == (H.FAILED, code)


