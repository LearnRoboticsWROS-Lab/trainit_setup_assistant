def test_every_case_reports_exactly_one_outcome_consistent_with_its_end(gate):
    """TSA 8.7.0 (vNext M4.5b, M4_5B_DESIGN.md §3): one "[BT] OUTCOME: <code>" per run, BIN_EMPTY only with SUCCESS /
    exit 0, every other outcome with FAILURE / exit 1; a TERMINAL_FAULT always after its FAULT line, never otherwise."""
    for case in CASES:
        run = gate['gate'].result(case.id)
        lines = [line for line in run.bt_lines if line.startswith('OUTCOME: ')]
        assert [ln.split(' -- ')[0] for ln in lines] == [f'OUTCOME: {OUTCOME[case.id]}'], run.why()
        assert lines[0].split(' -- ', 1)[1] == OPERATOR_TEXT[OUTCOME[case.id]], run.why()    # M4.5d F8
        ok = OUTCOME[case.id] == 'BIN_EMPTY'
        assert (run.base.finished, run.exit) == (('SUCCESS', 0) if ok else ('FAILURE', 1)), run.why()
        faulted = any(e.startswith('FAULT:') for e in run.events)
        assert faulted == (OUTCOME[case.id] == 'TERMINAL_FAULT'), run.why()


