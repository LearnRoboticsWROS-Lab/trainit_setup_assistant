"""The files a Canonical Task Program writes into ``<robot>_app`` (vNext M3.3, ADR-0024).

From the validated plan (``applications.task_program.plan_program``), never from the project
again, so a file can only say what was checked:

    config/bt_params.yaml        task_parameters: one entry per WAYPOINT (its target) with the move
                                 that reaches it (motion, planner mode, profile, speed, accel, via);
                                 a comment above each entry says which steps use it and how TSA
                                 resolved them
    config/paths.yaml            the PATHS (schema 1, TMR's path library): provider, continuity,
                                 profile, scalings, states, segments, and where a path stops for
                                 a process event (vNext M3.5)
    config/motion_profiles.yaml  the profiles TMR loads: the planning budget and goal tolerance of
                                 each application profile (scalings are per motion, above)
    README.md                    the program, readable: tasks, steps, waypoints, paths, providers,
                                 limits and the files

Deterministic: the same plan gives the same bytes (no time, no path of this machine, no version).
"""

from __future__ import annotations

